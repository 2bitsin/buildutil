def load_clang():
  """System libclang first, bundled wheel second.

  System wins because it matches the compiler actually in use — same dialect,
  same builtins — and because the wheel ships libclang.so with NO resource
  headers, so on its own every parse runs degraded with stddef.h missing.
  """
  try:
    import clang.cindex as ci
  except ImportError as exc:                                # pragma: no cover
    raise ClangUnavailable(
      "the reflect extension needs the clang python bindings; "
      "buildutil installs them into the project venv when the extension is "
      "declared in buildutil.toml") from exc

  library = os.environ.get("BUILDUTIL_LIBCLANG")
  if not library:
    library = _usable_system_libclang(_bindings_major())
  if library:
    try:
      ci.Config.set_library_file(library)
    except Exception:                                       # pragma: no cover
      pass
  resource = resource_dir()
  if resource is None:
    raise ClangUnavailable(NO_RESOURCE_DIR)
  return ci, resource


def _bindings_major() -> int:
  """Which libclang the installed python bindings were generated from.

  Older bindings against a newer library are fine -- the C API only grows.
  The reverse is not: 18.1.1 bindings on a clang-14 libclang.so abort with
  "check that your python bindings are compatible", which is exactly what a
  distro `apt install clang` hands you.
  """
  try:
    from importlib.metadata import version
    return int(version("libclang").split(".")[0])
  except Exception:
    return 0


def _usable_system_libclang(bindings_major: int) -> "str | None":
  found = _system_libclang()
  if not found:
    return None
  major = _clang_major()
  if bindings_major and major and major < bindings_major:
    # Too old for these bindings. Say so rather than crashing later inside
    # the parse, and let the bundled library take over.
    sys.stderr.write(
      "buildutil reflect: system clang {} is older than the python "
      "bindings ({}); using the bundled libclang instead\n".format(
        major, bindings_major))
    return None
  if not _exports_c_api(found):
    # Right name, wrong library. Debian's llvm layout keeps
    # libclang-cpp.so (the C++ API) beside libclang-XX.so (the C API the
    # bindings need), and a glob that means the latter can catch the
    # former -- seen live on the osxcross image, where the parse died at
    # first call with "undefined symbol: clang_annotateTokens". Probing
    # the symbol is the honest test; a name filter alone would only wait
    # for the next lookalike.
    sys.stderr.write(
      "buildutil reflect: {} does not export the libclang C API; "
      "using the bundled libclang instead\n".format(found))
    return None
  return found


def _exports_c_api(library: str) -> bool:
  """Does this shared object carry the C API the python bindings bind?

  Loading it is the probe -- cheap next to the parse that follows, and the
  only answer that cannot be fooled by a filename.
  """
  try:
    import ctypes
    return hasattr(ctypes.CDLL(library), "clang_createIndex")
  except OSError:
    return False


def _clang_major() -> "int | None":
  for name in ("clang", "clang++"):
    exe = shutil.which(name)
    if not exe:
      continue
    banner = _run([exe, "--version"]) or ""
    matched = re.search(r"clang version (\d+)", banner)
    if matched:
      return int(matched.group(1))
  return None


def _system_libclang() -> str | None:
  for name in ("clang", "clang++"):
    exe = shutil.which(name)
    if not exe:
      continue
    libdir = _run([exe, "-print-file-name=libclang.so"])
    for candidate in _libclang_candidates(Path(exe), libdir):
      if candidate and Path(candidate).is_file():
        return str(candidate)
  return None


def _libclang_candidates(exe: Path, printed: str | None):
  if printed and printed != "libclang.so":
    yield printed
  prefix = exe.resolve().parent.parent
  for sub in ("lib", "lib64"):
    for stem in ("libclang.so", "libclang.dylib", "libclang.dll"):
      yield prefix / sub / stem
  for pattern in ("libclang-*.so*", "libclang.so*"):
    for found in sorted((prefix / "lib").glob(pattern), reverse=True):
      # libclang-cpp.so is the C++ API and never what the bindings want;
      # reverse-sorting for "newest version first" would otherwise put it
      # ahead of libclang-18.so ('c' > '1').
      if not found.name.startswith("libclang-cpp"):
        yield found


def resource_dir() -> str | None:
  """clang's builtin include directory — stddef.h, stdint.h and friends.

  Without this the parse of any real header collapses; the pip wheel does not
  ship one, so it has to come from a clang on PATH either way.
  """
  told = os.environ.get("BUILDUTIL_RESOURCE_DIR")
  if told:
    return told if Path(told).is_dir() else None
  for name in ("clang", "clang++"):
    exe = shutil.which(name)
    if exe:
      found = _run([exe, "-print-resource-dir"])
      if found and Path(found).is_dir():
        return found
  return None


def sdk_path() -> str | None:
  """macOS: the SDK libclang has to be told about, or every parse loses the
  standard library.

  libc++ lives INSIDE the SDK
  (<sdk>/usr/include/c++/v1), and it is the clang DRIVER that injects
  `-isysroot` from xcrun -- libclang parsing a translation unit directly
  gets no such favour. Without it `<compare>`, `<cstdint>`, `<string>`
  and the rest resolve to nothing, every tagged type collapses, and the
  failure reads as a missing PROJECT include. Nothing to do off
  Apple: clang's builtin search finds /usr/include/c++/NN by itself.

  SDKROOT wins, because that is the variable the whole Apple toolchain
  already honours -- a conan profile setting `tools.apple:sdk_path`
  exports it, and so does anyone cross-building by hand. `xcrun` is the
  fallback and the normal case.
  """
  if platform.system() != "Darwin":
    return None
  from_env = os.environ.get("SDKROOT")
  if from_env and Path(from_env).is_dir():
    return from_env
  exe = shutil.which("xcrun")
  if exe:
    found = _run([exe, "--show-sdk-path"])
    if found and Path(found).is_dir():
      return found
  return None


def msvc_args() -> list[str]:
  """The Windows target and its standard library, including in Wine.

  vcvars supplies native INCLUDE. Wine's wrapper sets it only for cl's
  child process, so read the versions beside that wrapper and use its
  installation root in Unix spelling for the Linux libclang.
  """
  from buildutil.engine import _wine_msvc_live

  if platform.system() == "Windows":
    includes = [path.strip() for path in os.environ.get("INCLUDE", "").split(";")
                if path.strip()]
  elif _wine_msvc_live():
    wrapper = Path(shutil.which("cl"))
    root = (wrapper.parent / "../..").resolve()
    config = (wrapper.parent / "msvcenv.sh").read_text(encoding="utf-8")
    versions = dict(re.findall(r'^\s*(MSVCVER|SDKVER)=["\']?([\d.]+)',
                               config, re.MULTILINE))
    msvc = root / "vc/tools/msvc" / versions["MSVCVER"]
    sdk = root / "kits/10/include" / versions["SDKVER"]
    includes = [str(msvc / "include")]
    includes += [str(sdk / part) for part in ("ucrt", "shared", "um")]
  else:
    return []
  args = ["--target=x86_64-pc-windows-msvc",
          "-fms-compatibility", "-fms-extensions"]
  for path in includes:
    args += ["-isystem", path]
  return args


def _run(cmd: list[str]) -> str | None:
  try:
    done = subprocess.run(cmd, capture_output=True, text=True, check=False)
  except OSError:
    return None
  return done.stdout.strip() or None


def parse_args(std: str, includes: list[str],
               resource: str | None, sdk: str | None = None,
               msvc: list[str] | None = None) -> list[str]:
  # -Wno-unknown-attributes: the buildutil:: attributes are unknown to clang
  # BY DESIGN, so warning about them here is guaranteed noise -- and this
  # parse's diagnostics exist to explain a shortfall, where that noise would
  # bury the include that actually went missing. It costs nothing: the same
  # attributes are validated strictly by name against the buildutil
  # namespace, which is more than the warning ever did.
  args = ["-xc++", f"-std={std}", "-fparse-all-comments",
          "-Wno-unknown-attributes"]
  if resource:
    args += ["-resource-dir", resource]
  # See sdk_path(): on macOS the standard library is inside the SDK and
  # only the driver would have found it for us.
  if sdk:
    args += ["-isysroot", sdk]
  args += msvc or []
  args += [f"-I{path}" for path in includes]
  return args


def parse(ci, header: Path, args: list[str]):
  """Parse via a SYNTHESIZED TU, never the header as the main file.

  Clang ignores `#pragma once` in a main file, so a header whose own reflect
  file includes it back re-enters and redefines everything. Going through an
  unsaved `#include` also parses the header the way it is actually consumed.
  """
  stub = "_buildutil_reflect_tu.cpp"
  body = '#include "{}"\n'.format(header.as_posix())
  index = ci.Index.create()
  return index.parse(stub, args=args, options=_PARSE_OPTIONS,
                     unsaved_files=[(stub, body)])


def _is_invalid(ci, cursor) -> bool:
  """clang_isInvalidDeclaration is not in the python bindings, and it is the
  honest way to tell a degraded declaration from a good one — a parse that
  could not resolve a type does not lie silently, it flags the cursor."""
  try:
    fn = ci.conf.lib.clang_isInvalidDeclaration
    fn.argtypes = [type(cursor)]
    return bool(fn(cursor))
  except Exception:
    return False


# ---------------------------------------------------------------------------
# comments
# ---------------------------------------------------------------------------

_BLOCK_OPEN = re.compile(r"^/\*+[!<]?")
_BLOCK_CLOSE = re.compile(r"\*+/$")
_BLOCK_CONT = re.compile(r"^\s*\*+ ?")
_LINE = re.compile(r"^\s*//+[!<]?")

# One comment. A `/* */` block is one; a run of `//` lines is also ONE, since
# its lines share an indent that only means anything read together.
_ONE_COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*(?:\n[ \t]*//[^\n]*)*", re.DOTALL)


def _split_comments(text: str) -> list[str]:
  """`text` as the sequence of comments it is, or a single-element list.

  Adjacent blocks are ONE comment to the reader and several to the lexer,
  and what arrives here is the several: the delimiters belong to the block
  that wrote them and have to go one block at a time. Splitting is only
  safe when the matches cover everything but whitespace -- anything else is
  treated as one comment, whole.
  """
  parts, at = [], 0
  for found in _ONE_COMMENT.finditer(text):
    if text[at:found.start()].strip():
      return [text]
    parts.append(found.group())
    at = found.end()
  if text[at:].strip() or not parts:
    return [text]
  return parts


def normalize_comment(raw: str | None) -> str:
  """Strip the lexical markers and the common indentation, keep the text.

  Only the markers: this is the COMMENT, and what it means — a cli
  description, a serialization hint — is the consumer's call, not the
  reflector's. The continuation lines of a `//` run are column-aligned under
  the member they follow, so the marker has to be matched AFTER leading
  whitespace and the shared indent removed afterwards.

  A sequence of adjacent comments is stripped one comment at a time and the
  results joined: markers belong to the block that wrote them, and a run of
  blocks that shared one member's line would otherwise carry the interior
  `*/` and `/*` straight into the help text.
  """
  if not raw:
    return ""
  text = raw.strip()
  blocks = _split_comments(text)
  if len(blocks) > 1:
    return "\n".join(_strip_markers(block) for block in blocks).strip()
  return _strip_markers(text)


def _strip_markers(text: str) -> str:
  text = text.strip()
  if not text:
    return ""
  if text.startswith("/*"):
    text = _BLOCK_CLOSE.sub("", _BLOCK_OPEN.sub("", text))
    lines = [_BLOCK_CONT.sub("", line) if index else line
             for index, line in enumerate(text.splitlines())]
  else:
    lines = [_LINE.sub("", line) for line in text.splitlines()]

  lines = [line.rstrip() for line in lines]
  while lines and not lines[0].strip():
    lines.pop(0)
  while lines and not lines[-1].strip():
    lines.pop()
  if not lines:
    return ""

  body = [line for line in lines[1:] if line.strip()]
  indent = min((len(line) - len(line.lstrip()) for line in body), default=0)
  out = [lines[0].strip()]
  out += [line[indent:] if line.strip() else "" for line in lines[1:]]
  return "\n".join(out).strip()


# ---------------------------------------------------------------------------
# who a comment belongs to
# ---------------------------------------------------------------------------
#
# ONE model, from the raw tokens, for members, methods and enumerators alike.
# The alternative -- clang's raw_comment for some kinds and a token walk for
# others -- is where every comment bug in this file came from: raw_comment
# associates a trailing comment with a FIELD_DECL and NOTHING at all with a
# CXX_METHOD, so the two kinds disagreed about which comment beside a
# declaration was that declaration's, and each recovery of the difference
# grew its own edge cases.
#
# The rules below are clang's own (RawCommentList::addComment and
# getRawCommentForDeclNoCache), stated once, in the open, where they can be
# read and tested:
#
#   * comments separated by whitespace and at most one newline join into one
#     BLOCK -- but a trailing comment only absorbs the line under it when
#     that line's comment starts in the SAME COLUMN. That column rule is
#     what tells the aligned continuation of one member's comment from the
#     flush-left introduction of the next one's.
#   * a block INSIDE a declaration's extent is never that declaration's own:
#     it sits among the parameters, and parameter_comments owns it.
#   * a block after a declaration's end, on the line it ends on, TRAILS it.
#   * a block on the lines immediately above a declaration LEADS it.
#   * trailing wins; leading is the fallback. An explicit help annotation
#     overrides both, leaving the source comment free for a developer note.

_Block = collections.namedtuple(
  "_Block", "start line endline column trailing texts")


def comment_blocks(ci, owner) -> list:
  """The comment tokens of a body, joined into blocks the way clang joins
  them. Token SPELLINGS, kept apart: each block's delimiters are stripped
  per comment, so a run of `/* */` blocks cannot leak its interior `*/ /*`
  into the text."""
  try:
    tokens = [token
              for token in owner.translation_unit.get_tokens(extent=owner.extent)
              if token.kind == ci.TokenKind.COMMENT]
  except Exception:                                         # pragma: no cover
    return []
  source = _source_bytes(owner)
  if not source:                                            # pragma: no cover
    # Every rule below is read off the bytes between two tokens. With no
    # bytes to read there is no basis on which to join anything, and each
    # comment stands alone rather than being silently run together.
    return [_Block(token.extent.start.offset, token.extent.start.line,
                   token.extent.end.line, token.extent.start.column,
                   False, [token.spelling])
            for token in tokens]
  blocks: list = []
  end = 0
  for token in tokens:
    start = token.extent.start.offset
    trailing = _follows_code(source, start, end)
    block = _Block(start, token.extent.start.line, token.extent.end.line,
                   token.extent.start.column, trailing, [token.spelling])
    if blocks and _joins(source, end, block, blocks[-1]):
      blocks[-1].texts.append(token.spelling)
      blocks[-1] = blocks[-1]._replace(endline=block.endline)
    else:
      blocks.append(block)
    end = token.extent.end.offset
  return blocks


def _follows_code(source: bytes, start: int, previous_end: int) -> bool:
  """Is there CODE before this comment on its line? Another comment is not
  code: two blocks side by side on one line are one comment written twice,
  and clang treats them alike."""
  line_start = source.rfind(b"\n", 0, start) + 1
  before = source[line_start:start]
  if previous_end > line_start:
    before = before[previous_end - line_start:]
  return bool(before.strip())


def _joins(source: bytes, previous_end: int, block, previous) -> bool:
  between = source[previous_end:block.start]
  if between.strip() or between.count(b"\n") > 1:
    return False
  if previous.trailing == block.trailing:
    return True
  # A trailing comment reaches down only through its own column. Without
  # that, `int a { }; // about a` would swallow the flush-left `// about b`
  # written for the member under it.
  return previous.trailing and previous.column == block.column


def body_comments(ci, owner) -> dict:
  """Every comment in a class or enum body, by the declaration it describes.

  Keyed by a declaration's start OFFSET, exactly as the annotation model is:
  a cursor is not a stable dict key, and an offset names one declaration in
  one translation unit and nothing else.
  """
  ends: dict = {}
  starts: dict = {}
  spans = []
  for child in owner.get_children():
    where = child.extent
    spans.append((where.start.offset, where.end.offset))
    ends.setdefault(where.end.line, []).append(
      (where.end.offset, where.start.offset))
    starts.setdefault(where.start.line, where.start.offset)
  spans.sort()

  found: dict = {}
  for block in comment_blocks(ci, owner):
    if _within(spans, block.start):
      continue
    key = None
    if block.trailing:
      key = _ends_before(ends.get(block.line), block.start)
    if key is not None:
      found.setdefault(key, {}).setdefault("trailing", block)
      continue
    key = starts.get(block.endline + 1)
    if key is not None:
      found.setdefault(key, {}).setdefault("leading", block)
  return found


def _within(spans: list, offset: int) -> bool:
  at = bisect.bisect_right(spans, (offset, sys.maxsize)) - 1
  return at >= 0 and offset < spans[at][1]


def _ends_before(candidates, offset: int):
  """Which declaration on this line the comment trails: the one ending last
  before it. Two declarations may share a line (`RED = 1, BLUE`), and the
  comment belongs to the nearer."""
  best = None
  for end, key in candidates or ():
    if end <= offset and (best is None or end > best[0]):
      best = (end, key)
  return None if best is None else best[1]


def comment_of(comments: dict, cursor) -> str:
  """A declaration's comment: what trails it, else what leads it."""
  found = comments.get(cursor.extent.start.offset)
  if not found:
    return ""
  block = found.get("trailing") or found.get("leading")
  return normalize_comment("\n".join(block.texts))


def parameter_comments(ci, method) -> list[tuple[str, str, int]]:
  """operator() parameter comments, by token scan, with the offset that
  names each parameter to the annotation model.

  PARM_DECL.raw_comment is always None — clang associates comments with
  declarations, and a parameter is not one of the kinds it associates. The
  tokens are still there, so bucket COMMENT tokens by the source range
  between one parameter's end and the next parameter's start.
  """
  params = [c for c in method.get_children()
            if c.kind == ci.CursorKind.PARM_DECL]
  if not params:
    return []
  comments = [(t.spelling, t.extent.start.offset,
               t.extent.start.line, t.extent.end.line)
              for t in method.translation_unit.get_tokens(extent=method.extent)
              if t.kind == ci.TokenKind.COMMENT]
  out = []
  for index, param in enumerate(params):
    start = param.extent.end.offset
    stop = (params[index + 1].extent.start.offset
            if index + 1 < len(params) else method.extent.end.offset)
    hit = [entry for entry in comments if start <= entry[1] < stop]
    out.append((param.spelling, normalize_comment("\n".join(_adjacent(hit))),
                param.extent.start.offset))
  return out


def _adjacent(hits: list[tuple]) -> list[str]:
  """The leading run of comments that touch each other, by line.

  A parameter's comment may be written as several blocks under one another;
  a comment further down the argument list, past a blank line, belongs to
  whatever is written there and not to this parameter. The last parameter's
  range runs to the end of the method, so the run has to stop somewhere.
  """
  run, reach = [], None
  for text, _offset, first, last in hits:
    if reach is not None and first > reach + 1:
      break
    run.append(text)
    reach = last
  return run


_SOURCE_CACHE: dict[str, bytes] = {}


def _source_bytes(cursor) -> bytes:
  """The raw file a cursor came from, cached, as BYTES.

  Bytes rather than text because clang reports OFFSETS, and an offset is a
  byte count -- a header with a non-ASCII comment or string literal would
  slice at the wrong place through a str.
  """
  where = cursor.extent.start.file
  if where is None:
    return b""
  key = where.name
  if key not in _SOURCE_CACHE:
    try:
      _SOURCE_CACHE[key] = Path(key).read_bytes()
    except OSError:                                         # pragma: no cover
      _SOURCE_CACHE[key] = b""
  return _SOURCE_CACHE[key]


# ---------------------------------------------------------------------------
# who an annotation belongs to
# ---------------------------------------------------------------------------
#
# ONE model, from the raw tokens, for both tiers and every declaration kind --
# for the same reason the comment model above is one model: two readers of
# the same source disagree eventually, and every disagreement is a bug.
#
# It has to be the tokens, because libclang DROPS an unknown attribute from
# the AST entirely (and an empty macro was never in it to begin with). And a
# token run cannot simply be attached to whatever cursor contains it, because
# where clang puts a cursor's extent varies by kind:
#
#   class, enum       the attribute goes between the class-key and the name
#                     -- the only position the language allows -- so the
#                     cursor's extent INCLUDES it.
#   enumerator        a trailing attribute is OUTSIDE the extent, unless an
#                     `= value` stretches the extent over it.
#   member            a leading attribute is outside; a trailing one is in.
#   method            a leading attribute is outside, a trailing one inside
#                     -- and so are its parameters'.
#   parameter         both are outside the PARM_DECL and inside the method.
#
# So the rule is positional, exactly as it is for comment blocks: walk the
# enclosing scope's tokens, and bind each run to the declaration it touches
# -- the one before it, the one after it, or the one it sits inside. Inner
# scopes are asked first, so a run inside a method that a PARAMETER claims
# is never offered to the method.

_Token = collections.namedtuple("_Token", "text start end")
_Run = collections.namedtuple("_Run", "start end items")
_Annotations = collections.namedtuple(
  "_Annotations", "label tags help", defaults=(None,))

NO_ANNOTATIONS = _Annotations("", ())

_OPENERS = {"(": ")", "[": "]", "{": "}"}
_CLOSERS = set(_OPENERS.values())


def _token_list(ci, owner) -> list:
  try:
    return [_Token(token.spelling, token.extent.start.offset,
                   token.extent.end.offset)
            for token in owner.translation_unit.get_tokens(extent=owner.extent)]
  except Exception:                                         # pragma: no cover
    return []


def _place(origin: str, data: bytes, offset: int) -> str:
  return "{}:{}".format(origin or "<header>", data.count(b"\n", 0, offset) + 1)


def _closing(tokens: list, index: int, opener: str, closer: str) -> int:
  """Where the group opening at `index` closes, by index, or -1.

  Depth-counted rather than matched by shape, which is what lets one routine
  answer for `[[ ... ]]` (two opening tokens, since C++ has no `[[` token)
  and for a macro's argument list alike.
  """
  depth = 0
  for at in range(index, len(tokens)):
    if tokens[at].text == opener:
      depth += 1
    elif tokens[at].text == closer:
      depth -= 1
      if depth == 0:
        return at
  return -1


def _split_tokens(tokens: list) -> list:
  """A token sequence at its TOP-LEVEL commas."""
  parts, current, depth = [], [], 0
  for token in tokens:
    if token.text in _OPENERS:
      depth += 1
    elif token.text in _CLOSERS:
      depth -= 1
    if token.text == "," and depth == 0:
      parts.append(current)
      current = []
    else:
      current.append(token)
  if current:
    parts.append(current)
  return parts


def _arguments(tokens: list, data: bytes) -> tuple:
  """An argument clause's arguments, VERBATIM.

  Each is SLICED from the source between its first and last token rather
  than joined from the tokens themselves: `_Label(content-type)` lexes as
  three tokens and only the original bytes know they were written adjacent.
  """
  found = []
  for part in _split_tokens(tokens):
    if not part:
      continue
    text = data[part[0].start:part[-1].end].decode("utf-8", "replace").strip()
    found.append(_unquote(text))
  return tuple(found)


def _unquote(text: str) -> str:
  """A string literal's contents; anything else exactly as written. The
  attribute tier quotes (`label("system")`) and the macro tier does not
  (`_Label(system)`), and the two mean the same thing."""
  if len(text) >= 2 and text.startswith('"') and text.endswith('"'):
    return text[1:-1]
  return text


def _attribute_at(tokens: list, index: int, data: bytes, origin: str):
  """The `[[ ... ]]` specifier starting at `index`, as a run, or None."""
  if index + 1 >= len(tokens):
    return None
  if tokens[index].text != "[" or tokens[index + 1].text != "[":
    return None
  close = _closing(tokens, index, "[", "]")
  if close < 0:                                             # pragma: no cover
    return None
  return (_Run(tokens[index].start, tokens[close].end,
               _attribute_items(tokens[index + 2:close - 1], data, origin)),
          close + 1)


def _attribute_items(tokens: list, data: bytes, origin: str) -> list:
  """The buildutil annotations one specifier carries -- and only those.

  A foreign attribute produces no item and is not an error: `[[nodiscard]]`
  is not buildutil's business. It still counts as part of the RUN, so a
  buildutil attribute written beside one still reaches its declaration.
  """
  prefix = ""
  if len(tokens) > 2 and tokens[0].text == "using" and tokens[2].text == ":":
    # [[using buildutil: label("x"), meta("y")]] -- the namespace once, up
    # front, for every attribute in the list.
    prefix, tokens = tokens[1].text, tokens[3:]
  items = []
  for part in _split_tokens(tokens):
    item = _one_attribute(part, prefix, data, origin)
    if item is not None:
      items.append(item)
  return items


def _one_attribute(tokens: list, prefix: str, data: bytes, origin: str):
  if not tokens:
    return None
  namespace, name, rest = prefix, tokens[0].text, tokens[1:]
  if len(tokens) > 2 and tokens[1].text == "::":
    namespace, name, rest = tokens[0].text, tokens[2].text, tokens[3:]
  if namespace != ATTRIBUTE_NAMESPACE:
    return None
  kind = ATTRIBUTES.get(name)
  if kind is None:
    raise AnnotationError(
      "{}: unknown attribute [[{}::{}]] -- the {} attribute namespace "
      "defines exactly: {}".format(
        _place(origin, data, tokens[0].start), ATTRIBUTE_NAMESPACE, name,
        ATTRIBUTE_NAMESPACE, ", ".join(sorted(ATTRIBUTES))))
  if rest and rest[0].text == "(":
    close = _closing(rest, 0, "(", ")")
    if close > 0:
      return kind, _arguments(rest[1:close], data)
  return kind, ()


def _macro_at(tokens: list, index: int, data: bytes, macros: dict):
  """The annotation macro invocation starting at `index`, or None."""
  kind = macros.get(tokens[index].text)
  if kind is None or index + 1 >= len(tokens) or tokens[index + 1].text != "(":
    return None
  close = _closing(tokens, index + 1, "(", ")")
  if close < 0:                                             # pragma: no cover
    return None
  return (_Run(tokens[index].start, tokens[close].end,
               [(kind, _arguments(tokens[index + 2:close], data))]),
          close + 1)


def annotation_runs(tokens: list, data: bytes, macros: dict,
                    origin: str = "") -> list:
  """Every annotation in a token stream, as adjacent RUNS.

  Adjacent because that is how they bind: `[[nodiscard]] _Meta(hot) int x;`
  is one run of annotations between two declarations, and it is the run's
  outer edges -- not each specifier's -- that have to touch a declaration.
  """
  runs = []
  index = 0
  while index < len(tokens):
    found = (_attribute_at(tokens, index, data, origin)
             or _macro_at(tokens, index, data, macros))
    if found is None:
      index += 1
      continue
    run, index = found
    if runs and not data[runs[-1].end:run.start].strip():
      runs[-1] = runs[-1]._replace(end=run.end,
                                   items=runs[-1].items + run.items)
    else:
      runs.append(run)
  return runs


def _spans(cursors: list) -> list:
  """(start, end, key) per declaration, keyed by its own start offset -- the
  same key the comment model uses, and for the same reason: a cursor is not
  a stable dict key and an offset names one declaration exactly."""
  return [(c.extent.start.offset, c.extent.end.offset, c.extent.start.offset)
          for c in cursors]


def _bind(runs: list, spans: list, data: bytes) -> list:
  """Each run, paired with the declaration it annotates.

  Three positions, tried in the order in which they are unambiguous: a run
  the declaration's extent SWALLOWED (an enumerator's `= value` reaches over
  its trailing attribute, and a method's own trailing attribute is inside
  it), a run the declaration before it touches, and a run the declaration
  after it touches. Touching means whitespace and nothing else -- a comment
  or a comma in between and the run binds to nothing, exactly as a `_Label`
  separated from its declaration always has.
  """
  if not runs or not spans:
    return []
  inside = sorted(spans)
  starts = sorted((start, key) for start, _end, key in spans)
  ends = sorted((end, key) for _start, end, key in spans)
  bound = []
  for run in runs:
    key = _enclosing(inside, run)
    if key is None:
      key = _trails(ends, run, data)
    if key is None:
      key = _leads(starts, run, data)
    if key is not None:
      bound.append((run, key))
  return bound


def _enclosing(spans: list, run) -> "int | None":
  at = bisect.bisect_right(spans, (run.start, sys.maxsize, sys.maxsize)) - 1
  if at >= 0 and spans[at][1] >= run.end:
    return spans[at][2]
  return None


def _trails(ends: list, run, data: bytes) -> "int | None":
  at = bisect.bisect_right(ends, (run.start, sys.maxsize)) - 1
  if at < 0 or ends[at][0] > run.start:
    return None
  return None if data[ends[at][0]:run.start].strip() else ends[at][1]


def _leads(starts: list, run, data: bytes) -> "int | None":
  at = bisect.bisect_left(starts, (run.end, -1))
  if at >= len(starts):
    return None
  return None if data[run.end:starts[at][0]].strip() else starts[at][1]


def _fold(items: list) -> _Annotations:
  """Fold one declaration's label, ordered tags and optional help text."""
  by_kind = collections.defaultdict(list)
  help_items = [arguments for kind, arguments in items if kind is Annotation.HELP]
  if len(help_items) > 1:
    raise AnnotationError("duplicate buildutil::help on one declaration")
  for kind, arguments in items:
    by_kind[kind].extend(arguments)
  labels = by_kind[Annotation.LABEL]
  return _Annotations(labels[0] if labels else "",
                      tuple(by_kind[Annotation.META]),
                      (help_items[0][0] if help_items[0] else "")
                      if help_items else None)


def annotations_by_offset(ci, owner, macros: "dict | None" = None) -> dict:
  """Every annotation in a class or enum, by the declaration it describes.

  Keyed by START OFFSET, like the comment model. The OWNER's own key is its
  extent's start, so a type's own annotation is read back the same way its
  members' are.
  """
  data = _source_bytes(owner)
  if not data:                                              # pragma: no cover
    return {}
  macros = BUILTIN_MACROS if macros is None else macros
  where = owner.extent.start.file
  runs = annotation_runs(_token_list(ci, owner), data, macros,
                         where.name if where is not None else "")
  if not runs:
    return {}

  found = collections.defaultdict(list)
  # The type's OWN annotation sits between the class-key and the name -- the
  # one position the language allows for a class or an enum, and therefore
  # ahead of every declaration in the body.
  rest = []
  for run in runs:
    if run.end <= owner.location.offset:
      found[owner.extent.start.offset] += run.items
    else:
      rest.append(run)

  children = list(owner.get_children())
  claimed = set()
  for child in children:
    params = [c for c in child.get_children()
              if c.kind == ci.CursorKind.PARM_DECL]
    if not params:
      continue
    # A parameter's annotations live inside the METHOD's extent, and so does
    # the method's own trailing one. The inner scope is asked first, and
    # what it claims the outer one never sees.
    within = [run for run in rest
              if child.extent.start.offset <= run.start
              and run.end <= child.extent.end.offset]
    for run, key in _bind(within, _spans(params), data):
      found[key] += run.items
      claimed.add(run.start)

  for run, key in _bind([r for r in rest if r.start not in claimed],
                        _spans(children), data):
    found[key] += run.items
  folded = {key: _fold(items) for key, items in found.items()}
  if folded.get(owner.extent.start.offset, NO_ANNOTATIONS).help is not None:
    raise AnnotationError("buildutil::help is not supported on types: "
                          "type_scheme has no COMMENT")
  return folded


