def _code_only(text: str) -> str:
  """The header with comment bodies and literal contents blanked to spaces.

  A tag that was only ever TALKED about -- in a comment, in a doc string, in
  a static_assert message -- is not a tag, and while the tag was merely a
  yes/no question that distinction cost nothing to get wrong. It costs
  something now: the generator counts tags and holds its own output against
  the count, so a commented-out declaration would fail a build that is
  perfectly fine. Blanking is character-for-character and keeps newlines, so
  every offset still lines up with the original text.
  """
  out = list(text)
  size = len(text)
  index = 0

  def blank(start: int, stop: int) -> None:
    for at in range(max(start, 0), min(stop, size)):
      if out[at] != "\n":
        out[at] = " "

  def literal(start: int, quote: str) -> int:
    at = start + 1
    while at < size and text[at] != quote and text[at] != "\n":
      at += 2 if text[at] == "\\" else 1
    blank(start + 1, at)
    return min(at + 1, size)

  while index < size:
    char = text[index]
    after_word = index > 0 and (text[index - 1].isalnum()
                                or text[index - 1] == "_")
    if text.startswith("//", index):
      stop = text.find("\n", index)
      stop = size if stop < 0 else stop
      blank(index, stop)
      index = stop
    elif text.startswith("/*", index):
      stop = text.find("*/", index + 2)
      stop = size if stop < 0 else stop + 2
      blank(index, stop)
      index = stop
    elif char == "R" and not after_word and _RAW_OPEN_RE.match(text, index):
      raw = _RAW_OPEN_RE.match(text, index)
      close = ")" + raw.group(1) + '"'
      stop = text.find(close, raw.end())
      blank(raw.end(), size if stop < 0 else stop)
      index = size if stop < 0 else stop + len(close)
    elif char == '"':
      index = literal(index, char)
    elif char == "'" and not after_word:
      # 1'000 is a digit separator, not the start of a character literal
      index = literal(index, char)
    else:
      index += 1
  return "".join(out)


def _closing_paren(code: str, index: int) -> int:
  """The parameter list's own `)`, starting one character past its `(`."""
  depth = 1
  while index < len(code):
    if code[index] == "(":
      depth += 1
    elif code[index] == ")":
      depth -= 1
      if depth == 0:
        break
    index += 1
  return index


def _is_definition(code: str, close: int) -> bool:
  """A body follows the parameter list rather than a `;`. What may sit in
  between -- a trailing return type, noexcept -- carries neither."""
  for char in code[close + 1:]:
    if char in "{;":
      return char == "{"
  return False


def _tag_matches(code: str) -> list[tuple[str, bool]]:
  """Every tag-shaped entry point in already-blanked code, as (type name,
  is it a definition)."""
  found = []
  for match in TAG_RE.finditer(code):
    name = _TAG_NAME_RE.match(code, match.end())
    close = _closing_paren(code, match.end())
    found.append((name.group(1).split("::")[-1] if name else "",
                  _is_definition(code, close)))
  return found


def hand_written(text: str) -> set[str]:
  """The types this header answers for itself, by DEFINING the entry point
  and not merely declaring it. A second definition of `reflect_scheme(T*)`
  would collide with the first, so the generator emits nothing for those
  types and holds itself to nothing on their behalf.
  """
  if ENTRY not in text:
    return set()
  return {name for name, defined in _tag_matches(_code_only(text))
          if defined and name}


def tag_declarations(text: str) -> list[str]:
  """Every tag this header declares, named by the type it opts in -- and one
  entry per declaration even where the name cannot be read (the empty
  string), because the LENGTH is what the generator holds its output against.

  A type whose scheme this header DEFINES is not among them: the definition
  is the type's own answer, so it is neither a promise nor something the
  generator may emit a second time.

  The scan's "does this header carry the tag" and the generator's "how many
  did this header promise" are one call, so the two phases cannot drift:
  anything that changes what counts as a tag changes both at once, and a
  header the scan would never have selected can never be found short.
  """
  if ENTRY not in text:                       # the cheap prefilter, kept
    return []
  matches = _tag_matches(_code_only(text))
  written = {name for name, defined in matches if defined and name}
  return [name for name, defined in matches
          if not defined and name not in written]


def is_tagged(text: str) -> bool:
  """Cheap enough to run over every header in the tree: a substring test
  first, the regex only on the survivors."""
  return bool(tag_declarations(text))


def tagged_headers(sources: Path) -> list[Path]:
  found = []
  for path in sorted(sources.rglob("*")):
    if path.suffix not in HEADER_SUFFIXES or not path.is_file():
      continue
    if _skip_dir(path.relative_to(sources)):
      continue
    try:
      text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
      continue
    if is_tagged(text):
      found.append(path)
  return found


def _skip_dir(rel: Path) -> bool:
  """Mirrors buildutil.cmake's own exclusions — .archive/ and dot dirs are not
  part of the build, and *.install/ is data."""
  for part in rel.parts[:-1]:
    if part.startswith(".") or part.endswith(".install"):
      return True
  return False


REFLECT_SUFFIX = ".reflect.hpp"


def reflect_name(header: Path) -> str:
  """foo.hpp -> foo.reflect.hpp. Derivable without opening the file, which is
  what lets configure time know the output names."""
  return header.stem + REFLECT_SUFFIX


def reflect_rel(header: Path, sources: Path) -> str:
  """The sources-relative include spelling of a header's reflect file.
  `${CMAKE_BINARY_DIR}/generated` is already an include root on every module,
  so this resolves as-is -- from the detour, and from -include."""
  rel = header.relative_to(sources)
  return (rel.parent / reflect_name(header)).as_posix()


def detour_rel(header: Path, sources: Path) -> str:
  """Where a header's detour lands under the generated root: at THE SAME
  sources-relative path as the header itself.

  That collision is the mechanism, not an accident. The generated root sits
  ahead of sources/ on every include path, so one spelling reaches the
  detour instead of the header and every existing #include in the project
  keeps working, unedited."""
  return header.relative_to(sources).as_posix()


def detour(header: Path, sources: Path) -> str:
  """The wrapper: the real header, then its schemes.

  The real header is named by ABSOLUTE path. A relative one would have to be
  spelled against an include path -- and the only spelling that reaches it
  is the one this file exists to intercept, so it would include ITSELF.
  #include_next is the portable-looking alternative and is not portable:
  MSVC does not have it, and the windows cross lane is not optional. A build
  tree is per-machine anyway, so an absolute path costs nothing real.
  """
  own = detour_rel(header, sources)
  return ("// generated by buildutil — do not edit. The reflect detour for "
          "{own}:\n"
          "// the real header, then the schemes generated from it.\n"
          "#pragma once\n"
          '#include "{real}"\n'
          '#include "{schemes}"\n').format(
            own=own, real=header.as_posix(),
            schemes=reflect_rel(header, sources))


def direct_includes(text: str) -> list[str]:
  return _INCLUDE_RE.findall(text)


def include_directives(text: str) -> list[tuple[int, str, bool]]:
  """Every #include this file really has, as (line, spelling, quoted).

  Comment-aware, which direct_includes() has never needed to be: this one
  feeds a HARD ERROR, and refusing a build over a spelling that was commented
  out years ago is not a trade anyone would take. `_code_only` blanks in
  place, so an offset in the blanked text is the same offset in the real
  one -- the directive is read from the original and only its LIVENESS is
  asked of the copy.
  """
  code = _code_only(text)
  found = []
  for match in _INCLUDE_SPELLING_RE.finditer(text):
    hash_at = text.index("#", match.start())
    if code[hash_at] != "#":
      continue
    found.append((text.count("\n", 0, match.start()) + 1,
                  match.group(2), match.group(1) == '"'))
  return found


def bypasses(sources: Path, headers: list[Path]) -> list[tuple]:
  """Every include in the tree that would go around a detour.

  Two spellings do it, and they are the same mistake seen from two sides:

    #include "x.hpp"    quoted, from a file in the same directory. The
                        quoted form searches the INCLUDING FILE's own
                        directory before any -I path, so it finds the real
                        header and the detour never runs.

    #include <x.hpp>    bare, from inside the module that owns it. A
                        module's own directory is on its private include
                        path, and it is not the generated root -- so this
                        resolves under sources/ too.

  Both are refused by the same test -- does this spelling, resolved against
  the including file's directory, land on a tagged header? -- and the fix
  for both is the same: spell it sources-relative, which is the only
  spelling the detour answers to.

  Returned rather than raised, one entry per site, so a project migrating
  gets the whole list in one configure instead of one per run.
  """
  tagged = {header.resolve(): header for header in headers}
  if not tagged:
    return []
  found = []
  for path in sorted(sources.rglob("*")):
    if path.suffix not in HEADER_SUFFIXES + SOURCE_SUFFIXES:
      continue
    if not path.is_file() or _skip_dir(path.relative_to(sources)):
      continue
    try:
      text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:                                          # pragma: no cover
      continue
    for line, spelling, quoted in include_directives(text):
      try:
        candidate = (path.parent / spelling).resolve()
      except OSError:                                        # pragma: no cover
        continue
      header = tagged.get(candidate)
      if header is None:
        continue
      correct = detour_rel(header, sources)
      # An ANGLE include never searches the including file's own directory,
      # so resolving it there is a PROXY for "some -I root shorter than
      # sources/ reaches it" -- true for the module's own dir, and the
      # reason a bare <x.hpp> is caught. When the spelling already IS the
      # sources-relative one there is no shorter root in play and the
      # generated root wins, so that case is fine and only the quoted form
      # of it is not.
      if not quoted and spelling == correct:
        continue
      found.append((path, line, spelling, quoted, correct))
  return found


def bypass_message(root: Path, found: list[tuple]) -> str:
  lines = ["buildutil reflect: {} include(s) reach a reflected header "
           "without its detour".format(len(found)), ""]
  for path, line, spelling, quoted, correct in found:
    opener, closer = ('"', '"') if quoted else ("<", ">")
    lines += ["  {}:{}: #include {}{}{}".format(
                _posix(path, root), line, opener, spelling, closer),
              '      write:  #include "{}"'.format(correct)]
  lines += [
    "",
    "  A reflected header is reached through a generated DETOUR that adds",
    "  its schemes, and the generated root sits ahead of sources/ on the",
    "  include path so one sources-relative spelling finds it. These do not",
    "  use that spelling: a quoted include searches the including file's own",
    "  directory first, and a bare one is answered by the module's own",
    "  include root -- either way the real header arrives WITHOUT its",
    "  schemes, and a type that is reflected everywhere else is silently not",
    "  reflected here.",
    ""]
  return "\n".join(lines) + "\n"


def sources_needing(source_files: list[Path], headers: list[Path],
                    sources: Path, mode: str = "direct",
                    preprocess: "callable | None" = None
                    ) -> dict[Path, list[Path]]:
  """Which .cpp needs which reflect headers.

  `direct` reads each .cpp's own #include lines — no preprocessor, no second
  pass. It misses a reflected header reached transitively, but that miss is a
  COMPILE ERROR (the entry point's deduced return type is used before its
  definition), never a silent wrong answer, and the fix is to include the
  header you are actually using.

  `preprocess` asks the compiler for the real closure. Correct always, and
  costs a preprocessor run per TU.
  """
  by_spelling: dict[str, Path] = {}
  for header in headers:
    rel = header.relative_to(sources).as_posix()
    by_spelling[rel] = header
    by_spelling[header.name] = header

  mapping: dict[Path, list[Path]] = {}
  for source in source_files:
    if mode == "preprocess" and preprocess is not None:
      reached = preprocess(source)
      hit = [h for h in headers if h in reached]
    else:
      try:
        text = source.read_text(encoding="utf-8", errors="replace")
      except OSError:
        continue
      seen, hit = set(), []
      for spelling in direct_includes(text):
        header = by_spelling.get(spelling)
        if header is None:
          # a quoted sibling include resolves against the includer's directory
          candidate = (source.parent / spelling).resolve()
          header = next((h for h in headers if h.resolve() == candidate), None)
        if header is not None and header not in seen:
          seen.add(header)
          hit.append(header)
    if hit:
      mapping[source] = hit
  return mapping


def preprocessor_closure(compiler: str, source: Path,
                         args: list[str]) -> set[Path]:
  """The `preprocess` scan mode: -M gives the transitive include closure."""
  cmd = [compiler, "-M", "-MG", *args, str(source)]
  try:
    out = subprocess.run(cmd, capture_output=True, text=True,
                         check=False).stdout
  except OSError:
    return set()
  out = out.replace("\\\n", " ")
  _, _, rhs = out.partition(":")
  return {Path(tok).resolve() for tok in rhs.split() if tok}


def declarations(headers: list[Path], sources: Path, root: Path,
                 mapping: dict[Path, list[Path]],
                 detours: bool = True) -> str:
  """The scan's output: literal cmake calls, so the extension parses nothing.

  A manifest would need file(STRINGS) plus splitting; a generated .cmake of
  function calls is the same information with the parsing already done.

  The detour spelling is passed even though cmake could derive it, for the
  same reason every other path here is: one side works out what the files
  are called, and it is this one.
  """
  lines = ["# generated by buildutil — do not edit.",
           "# _buildutil_reflect_declare(<header> <reflect-rel> "
           "<detour-rel> <users...>)"]
  users: dict[Path, list[Path]] = {}
  for source, hit in mapping.items():
    for header in hit:
      users.setdefault(header, []).append(source)
  for header in headers:
    who = ";".join(_posix(p, root) for p in sorted(users.get(header, [])))
    lines.append('_buildutil_reflect_declare("{}" "{}" "{}" "{}")'.format(
      _posix(header, root), reflect_rel(header, sources),
      detour_rel(header, sources) if detours else "", who))
  return "\n".join(lines) + "\n"


def _posix(path: Path, root: Path) -> str:
  try:
    return path.relative_to(root).as_posix()
  except ValueError:
    return path.as_posix()


