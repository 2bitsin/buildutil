_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "", "\t": "\\t"}


def cxx_string(text: str) -> str:
  return '"' + "".join(_ESCAPES.get(ch, ch) for ch in text) + '"'


def _tag_list(ns: str, tags) -> str:
  return "::{}::tag_list<{}>".format(
    ns, ", ".join(cxx_string(tag) for tag in tags))


def _written(*entries) -> list:
  """Trailing template arguments, with the DEFAULTED tail dropped.

  Each entry is (written, default). Template arguments are positional, so a
  default in the MIDDLE still has to be spelled out and only the run at the
  end may go -- which is what keeps a declaration carrying neither a label
  nor a tag emitting precisely the bytes it emitted before either existed.
  """
  kept = list(entries)
  while kept and kept[-1][0] == kept[-1][1]:
    kept.pop()
  return [written for written, _default in kept]


def _tail(ns: str, label: str, tags) -> str:
  return "".join(", " + written for written in _written(
    (cxx_string(label), '""'), (_tag_list(ns, tags), _tag_list(ns, ()))))


class Reflected:
  """One tagged type, in the shape the emitter needs."""

  def __init__(self, name, namespaces, template_params, members, params,
               methods=(), bases=(), label="", tags=()):
    self.name = name
    self.namespaces = namespaces
    self.template_params = template_params
    self.members = members            # [(name, comment, encapsulated, is_reference, label, tags)]
    self.params = params              # [(name, comment, label, tags)] or None
    self.methods = list(methods)      # [(name, comment, [param...], label, tags)]
    self.bases = list(bases)          # ["::ns::Base", ...] in declaration order
    self.label = label                # what the TYPE itself was annotated with
    self.tags = tuple(tags)

  @property
  def qualified(self) -> str:
    return "::".join([*self.namespaces, self.name])

  @property
  def spelling(self) -> str:
    """How to name the type inside its own namespace, with the template
    parameters re-applied for a class template."""
    if not self.template_params:
      return self.name
    return "{}<{}>".format(self.name, ", ".join(self.template_params))


class ReflectedEnum:
  """One tagged enum. It carries no pointer-to-member and no access, so it
  is a different record from Reflected rather than a special case of it."""

  def __init__(self, name, namespaces, enumerators, label="", tags=()):
    self.name = name
    self.namespaces = namespaces
    self.enumerators = enumerators     # [(name, comment, label, tags)]
    self.label = label                 # what the ENUM itself was annotated with
    self.tags = tuple(tags)

  @property
  def spelling(self) -> str:
    return self.name


def collect_enums(ci, tu, header: Path,
                  macros: "dict | None" = None) -> list[ReflectedEnum]:
  """Tagged enums.

  An enum cannot befriend anything -- there is no member-declaration list --
  so it opts in with a plain declaration of the entry point beside it:

      enum class Colour { RED, GREEN };
      constexpr auto reflect_scheme(Colour*);

  which needs no friendship because enumerators are public anyway. Finding
  it is therefore a search for a namespace-scope declaration rather than for
  a child cursor, but it is the same literal and the same grep.
  """
  target = header.resolve()
  enums: dict[int, tuple] = {}
  tagged: set[int] = set()

  def visit(cursor, namespaces):
    for child in cursor.get_children():
      loc = child.location.file
      if loc is None or Path(loc.name).resolve() != target:
        if child.kind == ci.CursorKind.NAMESPACE:
          visit(child, [*namespaces, child.spelling])
        continue
      if child.kind == ci.CursorKind.NAMESPACE:
        visit(child, [*namespaces, child.spelling])
      elif child.kind == ci.CursorKind.ENUM_DECL and child.spelling:
        enums[child.hash] = (child, list(namespaces))
      elif child.kind == ci.CursorKind.FUNCTION_DECL and child.spelling == ENTRY:
        params = [c for c in child.get_children()
                  if c.kind == ci.CursorKind.PARM_DECL]
        if len(params) == 1:
          pointee = params[0].type.get_pointee()
          declared = pointee.get_declaration()
          if declared is not None and declared.kind == ci.CursorKind.ENUM_DECL:
            tagged.add(declared.hash)

  visit(tu.cursor, [])

  # DECLARATION ORDER, which is the order `enums` was filled in. `tagged` is
  # a set of cursor hashes and iterates in an order nothing in the source
  # controls, so driving the emission from it makes the same header produce
  # a differently ordered file run to run -- which restamps that file, and
  # rebuilds every translation unit including it, for no change at all.
  found = []
  for key, (cursor, namespaces) in enums.items():
    if key not in tagged:
      continue
    if _is_invalid(ci, cursor):
      continue
    notes = annotations_by_offset(ci, cursor, macros)
    comments = body_comments(ci, cursor)
    items = []
    for child in cursor.get_children():
      if child.kind != ci.CursorKind.ENUM_CONSTANT_DECL:
        continue
      note = notes.get(child.extent.start.offset, NO_ANNOTATIONS)
      items.append((child.spelling,
                    note.help if note.help is not None
                    else comment_of(comments, child),
                    note.label, note.tags))
    own = notes.get(cursor.extent.start.offset, NO_ANNOTATIONS)
    found.append(ReflectedEnum(cursor.spelling, namespaces, items,
                               own.label, own.tags))
  return found


def collect(ci, tu, header: Path,
            macros: "dict | None" = None) -> list[Reflected]:
  found: list[Reflected] = []
  target = header.resolve()

  def visit(cursor, namespaces):
    for child in cursor.get_children():
      loc = child.location.file
      kind = child.kind
      if kind == ci.CursorKind.NAMESPACE:
        visit(child, [*namespaces, child.spelling])
        continue
      if kind not in (ci.CursorKind.STRUCT_DECL, ci.CursorKind.CLASS_DECL,
                      ci.CursorKind.CLASS_TEMPLATE):
        continue
      if loc is None or Path(loc.name).resolve() != target:
        continue
      if _tagged(ci, child) and not _is_invalid(ci, child):
        entry = _describe(ci, child, namespaces, macros)
        if entry is not None:
          found.append(entry)
      visit(child, namespaces)

  visit(tu.cursor, [])
  return found


def _tagged(ci, cursor) -> bool:
  for child in cursor.get_children():
    if "FRIEND" not in child.kind.name:
      continue
    tokens = " ".join(t.spelling for t in child.get_tokens())
    if ENTRY in tokens:
      return True
  return False


def _is_plain_method(ci, cursor) -> bool:
  """Public, non-static, not an operator, not a special member.

  Constructors and destructors are their own cursor kinds, and a templated
  method is a FUNCTION_TEMPLATE -- neither reaches here. What is left to
  exclude is operator= / conversion operators (CXX_METHOD named operator*)
  and statics, whose pointer type is not a pointer-to-member.
  """
  return (cursor.access_specifier.name == "PUBLIC"
          and not cursor.spelling.startswith("operator")
          and not cursor.is_static_method())


# Canonical spellings clang can print but nobody can write back. The first
# is how a DEPENDENT type prints once desugared (`Box<type-parameter-0-0>`);
# the parenthesised ones are clang's placeholders for entities that have no
# writable name at all.
_UNWRITABLE = ("type-parameter-", "(anonymous", "(unnamed", "(lambda")


def _is_virtual_base(ci, base) -> bool:
  """`Cursor.is_virtual_base()` is not in every generation of the python
  bindings — the libclang 18.1.1 wheel buildutil pins does not have it — but
  clang_isVirtualBase has been in the C API forever and cindex's own function
  table already declares its signature. So ask the library directly when the
  python sugar is missing, the same way _is_invalid does."""
  method = getattr(base, "is_virtual_base", None)
  if method is not None:
    return bool(method())
  try:
    return bool(ci.conf.lib.clang_isVirtualBase(base))
  except Exception:                                         # pragma: no cover
    # Not being able to ask is no reason to drop the base: an unlisted base
    # is invisible to every consumer, while a wrongly listed virtual one is
    # at worst visited twice by a fold.
    return False


def _base_name(ci, base, template_params) -> "str | None":
  """How to name one base in a base_list, or None if it is not captured.

  Direct, public, non-virtual only — the support header's prose says why.
  """
  if base.access_specifier.name != "PUBLIC":
    return None
  if _is_virtual_base(ci, base):
    return None

  # `type.get_canonical()` is the one spelling that survives the move into
  # another file: it is fully qualified and alias-free. libclang's `spelling`
  # is the SOURCE spelling, so a base written `Local` inside namespace demo
  # comes back as `Local` — which resolves to the wrong thing, or to nothing,
  # from anywhere else. Canonical gives `demo::Local`, and `using Alias =
  # acme::Base` gives `acme::Base`. The leading `::` closes the last gap: a
  # nested namespace of the same name would otherwise win the lookup.
  canonical = base.type.get_canonical().spelling
  if canonical and not any(bad in canonical for bad in _UNWRITABLE):
    return "::" + canonical

  # A base that mentions one of the class's own template parameters has no
  # canonical spelling to write — clang desugars `Box<T>` all the way to
  # `Box<type-parameter-0-0>`. The source spelling does work here, and only
  # here: the list is emitted at the same namespace scope the class was
  # declared at, under a re-applied copy of the same template head.
  written = base.type.spelling
  if not written:
    return None
  if "::" in written and written.split("::", 1)[0].strip() in template_params:
    # `T::inner` is a dependent qualified name, and a template argument is
    # not one of the contexts where C++20 made `typename` optional.
    return "typename " + written
  return written


def _describe(ci, cursor, namespaces,
              macros: "dict | None" = None) -> "Reflected | None":
  template_params = []
  if cursor.kind == ci.CursorKind.CLASS_TEMPLATE:
    for child in cursor.get_children():
      if child.kind == ci.CursorKind.TEMPLATE_TYPE_PARAMETER:
        template_params.append(child.spelling)
      elif child.kind in (ci.CursorKind.TEMPLATE_NON_TYPE_PARAMETER,
                          ci.CursorKind.TEMPLATE_TEMPLATE_PARAMETER):
        # A value or template parameter has to be reproduced with its own
        # type, which means naming a type — the one thing this generator
        # refuses to do. Skipping is honest; emitting a guess is not.
        return None

  members, params, calls, bases = [], None, [], []
  named_methods: dict = {}
  comments = body_comments(ci, cursor)
  notes = annotations_by_offset(ci, cursor, macros)

  def said(child) -> _Annotations:
    return notes.get(child.extent.start.offset, NO_ANNOTATIONS)

  def described(method) -> list:
    """One method's parameters, with their comments and annotations."""
    return [(name, notes[at].help if at in notes and notes[at].help is not None
             else comment, notes.get(at, NO_ANNOTATIONS).label,
             notes.get(at, NO_ANNOTATIONS).tags)
            for name, comment, at in parameter_comments(ci, method)]

  for child in cursor.get_children():
    if child.kind == ci.CursorKind.CXX_BASE_SPECIFIER:
      # Base specifiers arrive before the members, in the order they were
      # written, which is the order the list has to keep: the consumer's
      # fold over the bases is the class's own inheritance order.
      base = _base_name(ci, child, template_params)
      if base is not None:
        bases.append(base)
    elif child.kind == ci.CursorKind.FIELD_DECL:
      if _is_invalid(ci, child):
        continue
      note = said(child)
      members.append((child.spelling,
                      note.help if note.help is not None
                      else comment_of(comments, child),
                      child.access_specifier.name != "PUBLIC",
                      child.type.kind == ci.TypeKind.LVALUEREFERENCE,
                      note.label, note.tags))
    elif child.kind == ci.CursorKind.CXX_METHOD:
      if child.spelling == "operator()":
        calls.append(child)
      elif _is_plain_method(ci, child):
        named_methods.setdefault(child.spelling, []).append(child)

  # Overloads are refused rather than guessed at: cli arguments arrive as
  # strings and the target's types drive the parse, so with two call
  # operators there is no basis on which to pick one.
  # An empty list and "no call operator at all" are DIFFERENT answers, so
  # the zero-parameter case still gets a scheme: a command declaring
  # `operator()()` means "I take nothing", which a caller must be able to
  # enforce, and that is not the same as a type with no call operator.
  if len(calls) == 1:
    params = described(calls[0])

  methods = []
  for name, found in named_methods.items():
    if len(found) > 1:
      # No single &T::Name exists, so there is no address to emit. Say so
      # rather than guessing or failing the whole type: the other methods
      # still reflect, and subcommand resolution never considered
      # overloads anyway.
      sys.stderr.write(
        "buildutil reflect: {}::{} is overloaded ({} declarations) -- "
        "skipped; reflection needs one address per name\n".format(
          cursor.spelling, name, len(found)))
      continue
    methods.append((name,
                    said(found[0]).help if said(found[0]).help is not None
                    else comment_of(comments, found[0]),
                    described(found[0]),
                    said(found[0]).label,
                    said(found[0]).tags))

  own = notes.get(cursor.extent.start.offset, NO_ANNOTATIONS)
  return Reflected(cursor.spelling, namespaces, template_params, members,
                   params, methods, bases, own.label, own.tags)


def emit(entries: list[Reflected], header_include: str,
         namespace: str = "reflect",
         enums: "list[ReflectedEnum] | None" = None,
         back_include: bool = True) -> str:
  out = ["// generated by buildutil from {} — do not edit.".format(
           header_include),
         "#pragma once",
         "",
         "#include <_buildutil/reflect.hpp>"]
  # Including the described header BACK is what a force-included reflect
  # header needs and what a detoured one must not have. Force-included, this
  # file is the first thing in the translation unit and would otherwise name
  # a type nobody has declared yet. Behind a detour it is included one line
  # after that same header, so the back-include is a `#pragma once` no-op --
  # and a line of noise that sends a reader looking for a cycle.
  if back_include:
    out.append('#include <{}>'.format(header_include))
  out.append("")
  for enum in enums or []:
    out += _emit_enum(enum, namespace)
  for entry in entries:
    out += _emit_one(entry, namespace)
  return "\n".join(out)


def _emit_type_scheme(entry, ns: str, head: str = "") -> list[str]:
  """What the TYPE said about itself, on its own entry point.

  A class scheme is a pack of members and an enum scheme a pack of
  enumerators, so neither has a trailing parameter to grow. Emitted only
  where there is something to say, so a type that says nothing is byte for
  byte what it always was.
  """
  written = _written((cxx_string(entry.label), '""'),
                     (_tag_list(ns, entry.tags), _tag_list(ns, ())))
  if not written:
    return []
  return ["",
          "{}constexpr auto {}({}*)".format(head, TYPE_ENTRY, entry.spelling),
          "{",
          "  return ::{}::type_scheme<{}>{{ }};".format(
            ns, ", ".join(written)),
          "}"]


def _emit_enum(entry: "ReflectedEnum", ns: str) -> list[str]:
  open_ns = " ".join("namespace {} {{".format(n) for n in entry.namespaces)
  lines = []
  if open_ns:
    lines.append(open_ns)
  items = []
  for item in entry.enumerators:
    name, comment = item[0], item[1]
    label = item[2] if len(item) > 2 else ""
    tags = item[3] if len(item) > 3 else ()
    items.append(
      "    ::{ns}::enumerator<{name}, {type}::{item}, {comment}{tail}>".format(
        ns=ns, name=cxx_string(name), type=entry.name, item=name,
        comment=cxx_string(comment), tail=_tail(ns, label, tags)))
  lines.append("constexpr auto {}({}*)".format(ENTRY, entry.name))
  lines.append("{")
  lines.append("  return ::{}::enum_scheme<".format(ns))
  lines.append(",\n".join(items) if items else "    /* no enumerators */")
  lines.append("  >{ };")
  lines.append("}")
  lines += _emit_type_scheme(entry, ns)
  if entry.namespaces:
    lines.append("}" * len(entry.namespaces))
  lines.append("")
  return lines


def _emit_param(param, ns: str, indent: str = "    ") -> str:
  name, comment = param[0], param[1]
  label = param[2] if len(param) > 2 else ""
  tags = param[3] if len(param) > 3 else ()
  return "{indent}::{ns}::param_scheme<{name}, {comment}{tail}>".format(
    indent=indent, ns=ns, name=cxx_string(name), comment=cxx_string(comment),
    tail=_tail(ns, label, tags))


def _emit_one(entry: Reflected, ns: str) -> list[str]:
  open_ns = " ".join("namespace {} {{".format(n) for n in entry.namespaces)
  close_ns = "}" * len(entry.namespaces)
  head = ""
  if entry.template_params:
    head = "template <{}>\n".format(
      ", ".join("typename " + p for p in entry.template_params))

  lines = []
  if open_ns:
    lines.append(open_ns)

  # A reference member has no pointer-to-member to take, so it is named
  # by an accessor instead. `decltype(auto)` with the parenthesised return
  # keeps the result an lvalue reference to the referent, and `auto&&`
  # takes the owner however it is held -- so this names no type at all,
  # which is the property the whole generator is built on.
  items = []
  for member in entry.members:
    name, comment, enc = member[0], member[1], member[2]
    is_ref = member[3] if len(member) > 3 else False
    label = member[4] if len(member) > 4 else ""
    tags = member[5] if len(member) > 5 else ()
    reach = ("[](auto&& owner) -> decltype(auto) "
             "{{ return (owner.{member}); }}"
             if is_ref else "&{type}::{member}").format(
               type=entry.spelling, member=name)
    items.append(
      "    ::{ns}::member_scheme<{name}, {reach}, {comment}, {enc}{tail}>".format(
        ns=ns, name=cxx_string(name), reach=reach,
        comment=cxx_string(comment), enc="true" if enc else "false",
        tail=_tail(ns, label, tags)))
  # No noexcept, no consteval: the definition must match the friend
  # declaration's signature and specifiers EXACTLY, or it is a different
  # function and the tag silently declares one that never gets defined.
  lines.append("{}constexpr auto {}({}*)".format(head, ENTRY, entry.spelling))
  lines.append("{")
  if entry.bases:
    # Only a type that HAS captured bases gets the wider box. A type without
    # emits precisely what it emitted before bases existed, byte for byte,
    # so no already-generated header and no existing consumer moves.
    lines.append("  return ::{}::derived_scheme<".format(ns))
    lines.append("    ::{}::base_list<{}>{}".format(
      ns, ", ".join(entry.bases), "," if items else ""))
  else:
    lines.append("  return ::{}::class_scheme<".format(ns))
  lines.append(",\n".join(items) if items else "    /* no members */")
  lines.append("  >{ };")
  lines.append("}")
  lines += _emit_type_scheme(entry, ns, head)

  if entry.params is not None:
    call_items = [_emit_param(param, ns) for param in entry.params]
    lines.append("")
    lines.append("{}constexpr auto {}({}*)".format(
      head, CALL_ENTRY, entry.spelling))
    lines.append("{")
    lines.append("  return ::{}::call_scheme<".format(ns))
    lines.append(",\n".join(call_items) if call_items
                 else "    /* takes no arguments */")
    lines.append("  >{ };")
    lines.append("}")

  if entry.methods:
    method_items = []
    for method in entry.methods:
      name, comment, params = method[0], method[1], method[2]
      label = method[3] if len(method) > 3 else ""
      tags = method[4] if len(method) > 4 else ()
      inner = ",\n".join(_emit_param(param, ns, indent="        ")
                         for param in params)
      method_items.append(
        "    ::{ns}::method_scheme<{name}, &{type}::{member}, {comment},\n"
        "      ::{ns}::call_scheme<{params}>{tail}>".format(
          ns=ns, name=cxx_string(name), type=entry.spelling, member=name,
          comment=cxx_string(comment),
          params=("\n" + inner + "\n      ") if inner else "",
          tail=_tail(ns, label, tags)))
    lines.append("")
    lines.append("{}constexpr auto {}({}*)".format(
      head, INTERFACE_ENTRY, entry.spelling))
    lines.append("{")
    lines.append("  return ::{}::interface_scheme<".format(ns))
    lines.append(",\n".join(method_items))
    lines.append("  >{ };")
    lines.append("}")

  if close_ns:
    lines.append(close_ns)
  lines.append("")
  return lines


def depfile(output: Path, tu, header: Path) -> str:
  """A reflect file is invalidated by anything in its header's include
  closure, not just the header — the parse resolved through all of it."""
  deps = {header.resolve()}
  for entry in tu.get_includes():
    if entry.include is not None:
      deps.add(Path(entry.include.name).resolve())
  listed = " \\\n  ".join(sorted(str(p) for p in deps))
  return "{}: \\\n  {}\n".format(output, listed)


