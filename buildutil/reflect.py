"""C++ reflection codegen — the `reflect` cmake extension's python half.

A type opts in by befriending the generator's entry point:

    struct HelloWorld: Command
    {
      friend constexpr auto reflect_scheme(HelloWorld*);
      bool verbose{ false };   /* say more */
    };

That one line is the whole contract. It is real C++ (syntax-highlighted,
pinned to the type), it needs no include — an unqualified elaborated friend
declaration IS the declaration — it grants the generated code access to
private members, and a typo in the type name is a compile error rather than
a silent no-op. It is also a fixed literal string, so one grep selects both
the files worth parsing and the types within them.

How the schemes reach a translation unit -- the DETOUR
------------------------------------------------------

For every tagged header `sources/<rel>/x.hpp` the build emits TWO files into
the gitignored generated root:

    generated/<rel>/x.reflect.hpp   the schemes
    generated/<rel>/x.hpp           the DETOUR -- three directives under a
                                    comment saying what it is:

        // generated by buildutil — do not edit. The reflect detour for …
        #pragma once
        #include "/abs/path/to/sources/<rel>/x.hpp"
        #include "<rel>/x.reflect.hpp"

and the extension puts the generated root AHEAD of sources/ on every include
path. So `#include "<rel>/x.hpp"`, written anywhere, by anyone, at any depth
of the include graph, resolves to the detour: the real header first, its
schemes immediately after. The class and its schemes cannot be separated.

The real header is reached only through the ABSOLUTE spelling inside the
detour -- a path nobody hand-writes -- so there is exactly one way in. It is
also parsed IN PLACE, which is the whole reason this is a wrapper and not a
copy: its own relative includes still resolve, `__FILE__` still names it,
and a compiler error or a goto-definition in class code lands in the file
the author actually edits. Nothing under sources/ is generated, and nothing
generated is committed.

Untagged headers get no detour and resolve to sources/ as they always did.

One way in has to be the ONLY way in, and one spelling goes around it: a
quoted `#include "x.hpp"` from a file sitting NEXT TO the real header
resolves in the includer's own directory before any -I path, skipping the
detour. The scan refuses it by name, with file:line and the spelling to
use instead.

The deprecated force-include modes (`[reflect] include = source|module`)
remain one release as an escape hatch; a scheme they deliver per-TU can be
silently absent where a class is transitively reached.

Annotations -- what a declaration says beyond its name
------------------------------------------------------

A LABEL is an alternative EXTERNAL name; META tags are free-form text,
captured verbatim and never interpreted here. Both have TWO spellings that
mean the same thing: a real attribute in buildutil's own namespace
(`[[buildutil::label("secure")]]`, the ground truth, which every compiler
parses and ignores) and the `_Label` / `_Meta` macros that sugar it.

Both are read from the RAW token stream -- which reports source tokens
BEFORE macro expansion -- so what the sugar expands to never enters into it,
and `[reflect] annotation` can move a project from one expansion to the
other with nothing else changing. An attribute in the buildutil namespace
that is not one of ours is a hard error naming it and the valid set: in
attribute mode the compiler's own unknown-attribute warning is off, so this
is the only thing left that can see a typo.

This module has two verbs, matching the two phases the cmake side needs:

  scan      cheap, configure time. Greps sources/ for the tag, derives each
            header's generated paths WITHOUT parsing, renders the support
            header, refuses any include spelling that would bypass a detour,
            and writes a .cmake file of _buildutil_reflect_declare() calls
            for the extension to include().

  generate  expensive, build time. libclang-parses one header and emits its
            reflect header and its detour, plus a depfile so the whole
            include closure is a dependency and not just the header itself.

The split exists because set_source_files_properties() runs at configure
time: the file NAMES must be known then, but the file CONTENTS need not be.

Three things about libclang that cost real time to find, all load-bearing:

  * Never parse the header as the main file. Clang ignores `#pragma once`
    there, so a header that circularly includes its own reflect file
    redefines everything in it. Synthesize `#include "..."` into an unsaved
    TU instead.
  * The pip libclang wheel ships libclang.so and no resource headers, so
    stddef.h is unresolvable and every parse runs degraded. Always pass
    -resource-dir from a real clang.
  * raw_comment answers for some declaration kinds and not others -- never
    for a PARM_DECL, never for a CXX_METHOD -- and where it does answer it
    can prefer a comment written among a declaration's own tokens to the
    one beside it. Comments are therefore read from the TOKENS, by one
    model that owns every kind (see "who a comment belongs to").
"""
