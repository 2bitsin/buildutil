def support_header(namespace: str = "reflect",
                   macros: "_MacroSource | None" = None) -> str:
  """buildutil's own, permanent, API surface for this feature.

  Emitted rather than shipped, so a project adopting reflection adds no
  dependency. The inline version namespace is not decoration: this header can
  end up in two packages built against different buildutil versions and meet
  in one TU, and coexisting beats one silently winning.

  It pulls in the macro header, so a translation unit that has the schemes
  also has the spellings that produce them -- which is what keeps every
  header already written against `#include <_buildutil/reflect.hpp> // for
  _Label` compiling untouched. A project that wants its own spellings turns
  the auto-include off ([reflect] macros).
  """
  macros = MACROS_BUILTIN if macros is None else macros
  note = _MACRO_NOTE[macros.kind].format(header=MACRO_HEADER)
  return (_SUPPORT.replace("@CALL_TRAITS@", _call_traits())
                  .replace("@MACROS@\n", note)
                  .replace("@NS@", namespace))


def _call_traits() -> str:
  """One specialization per qualifier combination.

  Written out rather than macro-generated: this ships into a project that
  wants no macros, and MSVC's traditional preprocessor warns C4003 on the
  empty-argument invocation a macro form would need.
  """
  # The full practical grid: cv x ref-qualifier x noexcept. A method that
  # returns a Command is a subcommand, and the author may spell it with any
  # of these -- a missing combination shows up as an incomplete-type error
  # pointing here rather than at their code.
  blocks = []
  grid = ["{}{}{}".format(cv, ref, ne)
          for cv in ("", " const")
          for ref in ("", " &", " &&")
          for ne in ("", " noexcept")]
  for qualifiers in grid:
    blocks.append(
      "  template <typename R, typename C, typename ... A>\n"
      "  struct call_traits<R (C::*)(A...){}>\n"
      "  {{\n"
      "    using result = R;\n"
      "    using owner  = C;\n"
      "    static constexpr std::size_t ARITY {{ sizeof...(A) }};\n"
      "    template <template <typename ...> class BOX>\n"
      "    using apply = BOX<A...>;\n"
      "  }};".format(qualifiers))
  return "\n\n".join(blocks)


_SUPPORT = r"""// generated by buildutil — do not edit.
#ifndef BUILDUTIL_REFLECT_V1_HPP
#define BUILDUTIL_REFLECT_V1_HPP

#include <array>
#include <cstddef>
#include <string_view>
#include <type_traits>

@MACROS@

namespace @NS@ { inline namespace v1 {

  // The char array is public because it has to be: a class type used as a
  // non-type template parameter must be a STRUCTURAL type, which means every
  // base and non-static data member is public and non-mutable. There is no
  // tidier version of this.
  template <std::size_t N>
  struct FixedString
  {
    char characters[N] {};

    constexpr FixedString(const char (&text)[N]) noexcept
    { for (std::size_t i = 0; i < N; ++i) characters[i] = text[i]; }

    constexpr auto view() const noexcept -> std::string_view
    { return std::string_view{ characters, N - 1 }; }
  };

  template <std::size_t N> FixedString(const char (&)[N]) -> FixedString<N>;

  // What a META annotation said -- verbatim, and in the order it was
  // written.
  //
  // The generator CAPTURES tags and never interprets one: what "internal"
  // or "since=2" means is the business of the library that reads it, and a
  // generator that guessed would have to be taught every consumer's
  // vocabulary. So this carries text and offers no opinion.
  template <FixedString ... TAG>
  struct tag_list
  {
    static constexpr std::size_t SIZE { sizeof...(TAG) };
    static constexpr std::array<std::string_view, sizeof...(TAG)> VALUES
      { TAG.view() ... };
  };

  // What a CLASS or an ENUM says about itself. A class scheme is a pack of
  // members and an enum scheme a pack of enumerators, so neither has a
  // trailing parameter to grow -- the type's own annotation rides its own
  // entry point instead, emitted only when there is something to say, and
  // `type_scheme_of` answers for the types that say nothing.
  template <FixedString Label = "", typename TAGS = tag_list<>>
  struct type_scheme
  {
    static constexpr std::string_view LABEL { Label.view() };
    using tags = TAGS;
  };

  // One member. Everything lives in the type, so the scheme itself is empty
  // and costs nothing to pass around. REFERENCE is an `auto` non-type
  // parameter, which is what lets the generator write `&T::x` without ever
  // naming x's type — the property that makes this portable.
  template <FixedString Name,
            auto        Reference,
            FixedString Comment      = "",
            bool        Encapsulated = false,
            FixedString Label        = "",
            typename    TAGS         = tag_list<>>
  struct member_scheme
  {
    static constexpr std::string_view NAME_STRING  { Name.view()    };
    static constexpr auto             REFERENCE    { Reference      };
    static constexpr std::string_view COMMENT      { Comment.view() };
    static constexpr bool             ENCAPSULATED { Encapsulated   };
    // EMPTY unless a label said otherwise. Empty is not the same as "equal
    // to NAME_STRING": it means NO external name was given, which leaves a
    // consumer free to derive one by its own convention (the cli dashes
    // underscores). A label is taken verbatim.
    static constexpr std::string_view LABEL        { Label.view()   };
    using tags = TAGS;
  };

  // One operator() parameter. No pointer-to-member exists for a parameter, so
  // this carries only what the language cannot supply; the TYPES come back
  // out of call_traits below.
  template <FixedString Name,
            FixedString Comment = "",
            FixedString Label   = "",
            typename    TAGS    = tag_list<>>
  struct param_scheme
  {
    static constexpr std::string_view NAME_STRING { Name.view()    };
    static constexpr std::string_view COMMENT     { Comment.view() };
    static constexpr std::string_view LABEL       { Label.view()   };
    using tags = TAGS;
  };

  // Reach a reflected member of a given owner.
  //
  // A member is normally named by a pointer-to-member, and `owner.*REF`
  // reaches it. A REFERENCE member cannot be: the language does not allow
  // a pointer-to-member to one ([dcl.mptr]/3), and that is a hard rule,
  // not a limitation of this generator. So for those the generator emits
  // a captureless accessor lambda instead -- a valid non-type template
  // argument, and one that still names no type it was not already given.
  //
  // This is the single place the difference is absorbed. Every consumer
  // reads a member the same way whichever kind it is.
  template <typename ITEM, typename OWNER>
  constexpr auto member_of(OWNER&& owner) -> decltype(auto)
  {
    if constexpr (std::is_member_object_pointer_v<decltype(ITEM::REFERENCE)>)
      return (owner.*(ITEM::REFERENCE));
    else
      return ITEM::REFERENCE(owner);
  }

  // One enumerator. VALUE is an `auto` non-type parameter for the same
  // reason REFERENCE is: the generator writes Colour::RED without naming
  // the underlying type, or std::int16_t, or anything else.
  template <FixedString Name, auto Value, FixedString Comment = "",
            FixedString Label = "", typename TAGS = tag_list<>>
  struct enumerator
  {
    static constexpr std::string_view NAME_STRING { Name.view()    };
    static constexpr auto             VALUE       { Value          };
    static constexpr std::string_view COMMENT     { Comment.view() };
    static constexpr std::string_view LABEL       { Label.view()   };
    using tags = TAGS;
  };

  template <typename ... PARAM> struct call_scheme { };

  // One public method. METHOD is its pointer-to-member-function, so the
  // consumer recovers the RETURN type through call_traits below and the
  // generator still never names a type -- which is what lets "a method
  // returning a Command is a subcommand" be decided entirely in C++.
  template <FixedString Name,
            auto        Method,
            FixedString Comment = "",
            typename    PARAMETERS = call_scheme<>,
            FixedString Label = "",
            typename    TAGS = tag_list<>>
  struct method_scheme
  {
    static constexpr std::string_view NAME_STRING { Name.view()    };
    static constexpr auto             METHOD      { Method         };
    static constexpr std::string_view COMMENT     { Comment.view() };
    static constexpr std::string_view LABEL       { Label.view()   };
    using parameters = PARAMETERS;
    using tags       = TAGS;
  };

  template <typename ... METHOD>     struct interface_scheme { };
  template <typename ... MEMBER>     struct class_scheme { };
  template <typename ... ENUMERATOR> struct enum_scheme  { };

  // What a type derives from, in declaration order.
  //
  // Only DIRECT, PUBLIC, NON-VIRTUAL bases are listed, and each of the
  // three limits earns its place. An indirect base is reachable by asking
  // the direct one in turn, so listing it here would only be a second,
  // desynchronisable path to the same answer. A protected or private base
  // is not part of the type's interface — no consumer may convert to it,
  // so naming it would hand out something unusable. And a virtual base is
  // SHARED, so a consumer folding over the lattice would meet the same
  // subobject through several branches with nothing in the vocabulary to
  // say they are one. A type that uses any of them still reflects; the
  // base is simply absent from this list.
  //
  // A listed base need NOT itself be reflected. A cli `Command` tag base
  // carries nothing and appears in every command's list; whether a base is
  // worth descending into is `reflected<BASE>`, which the consumer asks
  // and the generator cannot answer on its behalf.
  template <typename ... BASE> struct base_list { };

  // A class scheme that also carries its bases. A type with no captured
  // bases keeps emitting a plain `class_scheme`, byte for byte as before,
  // so this shape appears only where there is something extra to say.
  //
  // BASES comes first and is deliberately NOT one of the members: every
  // operation that counts or indexes members has an overload below that
  // steps over it, so code written against class_scheme keeps working
  // unchanged the day its type grows a base.
  template <typename BASES, typename ... MEMBER>
  struct derived_scheme { using bases = BASES; };

  template <template <typename ...> class BOX, typename ... ITEM>
  consteval auto scheme_size(BOX<ITEM...>) noexcept -> std::size_t
  { return sizeof...(ITEM); }

  // derived_scheme also matches the generic form above, with BASES as its
  // first ITEM — which would report one member too many. This overload is
  // more specialized, so partial ordering picks it, and "size" stays "how
  // many members" for every scheme there is.
  template <typename BASES, typename ... MEMBER>
  consteval auto scheme_size(derived_scheme<BASES, MEMBER...>) noexcept
    -> std::size_t
  { return sizeof...(MEMBER); }

  template <typename ... BASE>
  consteval auto bases_size(base_list<BASE...>) noexcept -> std::size_t
  { return sizeof...(BASE); }

#if defined(__cpp_pack_indexing) && __cpp_pack_indexing >= 202311L
  // clang defines the macro below C++26 too and then warns that using it is
  // an extension; the feature test IS the opt-in, so the warning is noise.
#if defined(__clang__)
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wc++26-extensions"
#endif
  template <std::size_t INDEX, template <typename ...> class BOX,
            typename ... ITEM>
  consteval auto scheme_item(BOX<ITEM...>) noexcept
  { return ITEM...[INDEX] { }; }

  template <std::size_t INDEX, typename BASES, typename ... MEMBER>
  consteval auto scheme_item(derived_scheme<BASES, MEMBER...>) noexcept
  { return MEMBER...[INDEX] { }; }

  // A base comes back as a TYPE, never as a value: a base is routinely
  // abstract, or has no default constructor, and neither is a reason for
  // it to be unreachable through reflection.
  template <std::size_t INDEX, typename ... BASE>
  consteval auto base_item(base_list<BASE...>) noexcept
  { return std::type_identity<BASE...[INDEX]> { }; }
#if defined(__clang__)
#pragma clang diagnostic pop
#endif
#else
  // MSVC has no C++26 core language support at all, so this branch is not
  // hypothetical. It is O(INDEX) instantiations where pack indexing is O(1);
  // that is the whole cost of the fallback.
  template <std::size_t INDEX, template <typename ...> class BOX,
            typename ITEM0, typename ... ITEMn>
  consteval auto scheme_item(BOX<ITEM0, ITEMn...>) noexcept
  {
    if constexpr (INDEX == 0u) { return ITEM0 { }; }
    else { return scheme_item<INDEX - 1u>(BOX<ITEMn...>{ }); }
  }

  // The rebuilt box KEEPS BASES. Dropping it would hand the next step to
  // the generic overload above, which would then read the base list as a
  // member — the fallback has to stay a derived_scheme the whole way down.
  template <std::size_t INDEX, typename BASES,
            typename ITEM0, typename ... ITEMn>
  consteval auto scheme_item(derived_scheme<BASES, ITEM0, ITEMn...>) noexcept
  {
    if constexpr (INDEX == 0u) { return ITEM0 { }; }
    else { return scheme_item<INDEX - 1u>(derived_scheme<BASES, ITEMn...>{ }); }
  }

  template <std::size_t INDEX, typename BASE0, typename ... BASEn>
  consteval auto base_item(base_list<BASE0, BASEn...>) noexcept
  {
    if constexpr (INDEX == 0u) { return std::type_identity<BASE0> { }; }
    else { return base_item<INDEX - 1u>(base_list<BASEn...>{ }); }
  }
#endif

  // The INDEXth base, unwrapped. Spelling the fold with this reads as
  // `base_at<I, decltype(BASES)>` where the member form reads
  // `decltype(scheme_item<I>(S))`, and both branches above feed it.
  template <std::size_t INDEX, typename BASES>
  using base_at = typename decltype(base_item<INDEX>(BASES{ }))::type;

  // True when a scheme exists AND has been generated. Both halves matter: a
  // tagged type whose reflect header was never produced has a declared but
  // undefined entry point, and using a deduced return type before its
  // definition is a substitution failure — so this correctly reports false
  // rather than handing back an empty scheme.
  template <typename T>
  concept reflected = requires { reflect_scheme(static_cast<T*>(nullptr)); };

  template <typename T>
  consteval auto scheme_of() noexcept
  {
    static_assert(reflected<T>,
      "type is not reflected. A class opts in from INSIDE itself with "
      "`friend constexpr auto reflect_scheme(YourType*);`; an enum has no "
      "member list to befriend, so it opts in from BESIDE itself with "
      "`constexpr auto reflect_scheme(YourEnum*);`. Also check that the "
      "project declares the reflect extension in buildutil.toml");
    return reflect_scheme(static_cast<T*>(nullptr));
  }

  // What T derives from. "No bases" is an ANSWER, not a failure: a plain
  // class_scheme has no `bases` member and this hands back an empty
  // base_list for it, so a consumer folds over every reflected type the
  // same way and never has to ask which shape it got.
  template <typename T> requires reflected<T>
  consteval auto bases_of() noexcept
  {
    // The raw ADL call rather than scheme_of<T>(): the constraint has
    // already made the same guarantee, and scheme_of is consteval, which
    // an unevaluated decltype has no business dragging in.
    using SCHEME = decltype(reflect_scheme(static_cast<T*>(nullptr)));
    if constexpr (requires { typename SCHEME::bases; })
      return typename SCHEME::bases { };
    else
      return base_list<> { };
  }

  // True when T was generated WITH bases. It says nothing about whether
  // those bases are themselves reflected — that is `reflected<BASE>`, one
  // question per base, and the consumer's to ask.
  template <typename T>
  concept has_reflected_bases =
    reflected<T> && (bases_size(bases_of<T>()) > 0u);

  // What T said about ITSELF -- its own label and its own tags, as opposed
  // to its members'. "Nothing" is an ANSWER here too: a type that says
  // nothing emits no entry point at all, and this hands back an empty
  // type_scheme for it, so every reflected type is asked the same way and
  // no consumer has to know which shape it got.
  template <typename T>
  consteval auto type_scheme_of() noexcept
  {
    if constexpr (requires { reflect_type_scheme(static_cast<T*>(nullptr)); })
      return reflect_type_scheme(static_cast<T*>(nullptr));
    else
      return type_scheme<> { };
  }

  template <typename T>
  concept interface_reflected =
    requires { reflect_interface_scheme(static_cast<T*>(nullptr)); };

  template <typename T>
  consteval auto interface_scheme_of() noexcept
  {
    static_assert(interface_reflected<T>,
      "type has no reflected methods: reflection captures public, "
      "non-special, non-template methods, and skips overloaded names "
      "because there is no single address to take");
    return reflect_interface_scheme(static_cast<T*>(nullptr));
  }

  template <typename T>
  concept callable_reflected =
    requires { reflect_call_scheme(static_cast<T*>(nullptr)); };

  template <typename T>
  consteval auto call_scheme_of() noexcept
  {
    static_assert(callable_reflected<T>,
      "type has no reflected operator(): it needs an accessible, "
      "non-overloaded, non-template call operator");
    return reflect_call_scheme(static_cast<T*>(nullptr));
  }

  // The parameter TYPES come from the language, not from the generator — so a
  // stale reflect header shows up as an arity mismatch instead of a help
  // screen that quietly disagrees with the function it documents.
  template <typename F> struct call_traits;

  // `static constexpr auto METHOD { … }` gives decltype a CONST-qualified
  // pointer, so every consumer would otherwise have to remove_cv before
  // asking anything about it.
  template <typename F> struct call_traits<F const> : call_traits<F> { };

@CALL_TRAITS@

  template <typename T>
  using call_traits_of = call_traits<decltype(&T::operator())>;

} }  // namespace @NS@::v1

#endif  // BUILDUTIL_REFLECT_V1_HPP
"""


# ---------------------------------------------------------------------------
# the annotation vocabulary, and the macro header that sugars it
# ---------------------------------------------------------------------------
#
# TWO TIERS, one meaning.
#
#   GROUND TRUTH   real C++ attributes in buildutil's own namespace --
#                  [[buildutil::label("system")]], [[buildutil::meta(...)]].
#                  Every compiler parses them and ignores them, and they are
#                  legal exactly where the language says an attribute may go.
#   SUGAR          `_Label(system)` / `_Meta(...)`, defined by the macro
#                  header below. Terser, and what every existing site writes.
#
# The generator reads BOTH, out of the RAW token stream -- which reports
# source tokens before macro expansion, so what the sugar expands to never
# enters into it. That is what makes the transition free: a macro that
# expands to nothing and a macro that expands to an attribute read
# identically here, and a hand-written attribute reads the same again.

class Annotation(enum.Enum):
  """What an annotation SAYS about the declaration it is written on.

  The value is the wire spelling -- the name inside the `buildutil::`
  attribute namespace -- and it is converted to this enum once, on the way
  in, so nothing downstream compares annotation text.
  """
  LABEL = "label"
  META = "meta"
  HELP = "help"


ATTRIBUTE_NAMESPACE = "buildutil"

# The WHOLE namespace, which is what makes strict validation possible: an
# attribute written in it that is not here is a typo, and a typo is a hard
# error rather than an annotation that silently does nothing.
ATTRIBUTES = {kind.value: kind for kind in Annotation}

# The macro spellings buildutil itself ships. A project whose own code
# already means something else by `_Label` writes its own file and points
# [reflect] macros at it; the spellings are then read back from that file.
BUILTIN_MACROS = {"_Label": Annotation.LABEL, "_Meta": Annotation.META,
                  "_Help": Annotation.HELP}

MACRO_HEADER = "_buildutil/reflect-macros.hpp"


class AnnotationError(Exception):
  """A `buildutil::` attribute buildutil does not define.

  Fatal, and deliberately so. In attribute mode clang's own unknown-attribute
  warning is off (its suppression has no namespace granularity), so this
  check IS the typo safety -- without it `[[buildutil::lable("x")]]` would
  compile clean, generate nothing, and surface as a missing name somewhere
  else entirely.
  """


class Expansion(enum.Enum):
  """What the shipped macros turn into. [reflect] annotation.

  It is also what the cmake side reads to decide whether this project's
  compiles need the unknown-attribute suppression -- which is why a project
  spelling its own macros still sets it: buildutil no longer writes the
  expansion, but it still has to know that attributes are in play.
  """
  MACRO = "macro"          # nothing at all -- the compiler never sees them
  ATTRIBUTE = "attribute"  # a real [[buildutil::...]] attribute


EXPANSIONS = {mode.value: mode for mode in Expansion}


class Macros(enum.Enum):
  """Where the macro spellings come from. [reflect] macros."""
  BUILTIN = "auto"   # buildutil writes them and the support header includes it
  NONE = "none"      # neither: attributes only, and the names stay free
  CUSTOM = "custom"  # the project's own file, by path


_MacroSource = collections.namedtuple("_MacroSource", "kind path")

MACROS_BUILTIN = _MacroSource(Macros.BUILTIN, None)

# The two spellings that are WORDS. Everything else is a path, so CUSTOM is
# deliberately not among them.
_MACRO_WORDS = {Macros.BUILTIN.value: Macros.BUILTIN,
                Macros.NONE.value: Macros.NONE}


def macro_source(spelling: str) -> _MacroSource:
  """`[reflect] macros`, read once. Anything that is not one of the two
  words is a PATH to the project's own macro file -- the escape hatch for a
  project whose `_Label` already means something else."""
  kind = _MACRO_WORDS.get((spelling or Macros.BUILTIN.value).strip())
  if kind is not None:
    return _MacroSource(kind, None)
  return _MacroSource(Macros.CUSTOM, Path(spelling.strip()))


def expansion(spelling: str) -> Expansion:
  """`[reflect] annotation`, read once."""
  mode = EXPANSIONS.get((spelling or Expansion.MACRO.value).strip())
  if mode is None:
    raise AnnotationError(
      "[reflect] annotation = {!r}: expected one of {}".format(
        spelling, ", ".join(sorted(EXPANSIONS))))
  return mode


# `#define NAME(` — the head of a function-like macro, which is the only
# shape an annotation spelling can have (it takes an argument).
_DEFINE_RE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)\(",
                        re.MULTILINE)
_SCOPED_RE = re.compile(re.escape(ATTRIBUTE_NAMESPACE) + r"\s*::\s*(\w+)")


def macro_spellings(source: _MacroSource) -> dict:
  """Which identifiers the generator reads as annotations.

  For buildutil's own header that is a constant. For a project's own file it
  is READ from the file: a macro is an annotation spelling because its
  replacement produces a `buildutil::` attribute, so the file that defines
  the sugar is also what teaches the generator to read it -- there is no
  second list to keep in step.
  """
  readers = {Macros.BUILTIN: lambda _: dict(BUILTIN_MACROS),
             Macros.NONE: lambda _: {},
             Macros.CUSTOM: _custom_spellings}
  return readers[source.kind](source.path)


def _custom_spellings(path: Path) -> dict:
  try:
    text = path.read_text(encoding="utf-8", errors="replace")
  except OSError as exc:
    raise AnnotationError(
      "[reflect] macros = {}: cannot be read ({})".format(path, exc)) from exc
  # A continued #define is one logical line, and its replacement -- the part
  # that says which attribute it produces -- is routinely on the second.
  joined = text.replace("\\\n", " ")
  found = {}
  for match in _DEFINE_RE.finditer(joined):
    stop = joined.find("\n", match.end())
    line = joined[match.end():] if stop < 0 else joined[match.end():stop]
    for name in _SCOPED_RE.findall(line):
      kind = ATTRIBUTES.get(name)
      if kind is None:
        raise AnnotationError(
          "{}: unknown attribute [[{}::{}]] -- the {} attribute namespace "
          "defines exactly: {}".format(path, ATTRIBUTE_NAMESPACE, name,
                                       ATTRIBUTE_NAMESPACE,
                                       ", ".join(sorted(ATTRIBUTES))))
      found[match.group(1)] = kind
  if not found:
    raise AnnotationError(
      "[reflect] macros = {}: defines no annotation macro. A macro is one by "
      "producing a {}:: attribute, as in\n"
      '    #define _MyLabel(x) [[{}::label(#x)]]\n'
      "and the generator reads the spellings back out of this file.".format(
        path, ATTRIBUTE_NAMESPACE, ATTRIBUTE_NAMESPACE))
  return found


def macro_header(mode: Expansion,
                 source: "_MacroSource | None" = None) -> str:
  """The shipped sugar, in whichever expansion the project asked for.

  Emitted beside the support header rather than baked into it, because this
  file is the ONE thing a project may replace -- and because the two
  expansions differ by nothing else.
  """
  source = MACROS_BUILTIN if source is None else source
  if source.kind is Macros.CUSTOM:
    return _MACRO_FORWARD.format(path=source.path.as_posix())
  label, meta, help_macro = _EXPANSIONS[mode]
  return _MACRO_TEMPLATE.format(label=label, meta=meta, help=help_macro,
                              prose=_EXPANSION_PROSE[mode])


_EXPANSIONS = {
  Expansion.MACRO: ("#define _Label(x)", "#define _Meta(...)", "#define _Help(x)"),
  Expansion.ATTRIBUTE: ("#define _Label(x)  [[buildutil::label(#x)]]",
                        "#define _Meta(...) [[buildutil::meta(__VA_ARGS__)]]",
                        "#define _Help(x)   [[buildutil::help(#x)]]"),
}

_EXPANSION_PROSE = {
  Expansion.MACRO: """\
// These expand to NOTHING. The compiler never sees them; the generator
// reads them out of the raw token stream, which reports source tokens
// BEFORE macro expansion. So they cost the build nothing, need no attribute
// support and no warning suppression -- and they are legal in positions the
// attribute they stand for is not, which is why they are still the default:
// `_Label(system) SYSTEM` is a LEADING enumerator attribute once expanded,
// and that is ill-formed. Move a site to the trailing spelling
// (`SYSTEM _Label(system)`) before turning expansion on; the generator has
// read both since the day the attribute tier landed.""",
  Expansion.ATTRIBUTE: """\
// These expand to REAL attributes, which every compiler parses and ignores
// -- so a misspelt annotation is caught by the generator (which validates
// the whole buildutil:: namespace strictly) rather than being silently
// dropped. The price is one warning per site, which buildutil silences for
// this project's compiles: gcc surgically (-Wno-attributes=buildutil::),
// clang bluntly (-Wno-unknown-attributes), MSVC per-warning (/wd5030).
//
// An attribute is legal only where the language says: after the class-key
// for a class or an enum (`struct [[...]] S`), TRAILING for an enumerator
// (`SYSTEM [[...]]`, ahead of any `= value`), and either side of a member,
// a method or a parameter.""",
}

_MACRO_INCLUDED = """\
// The annotation vocabulary -- LABEL, an external name for a declaration,
// META, free-form tags, and HELP, explicit comment text -- uses the macro
// header, which is included here so that a translation unit holding the
// schemes also holds what produces them.
#include <{header}>
"""

_MACRO_ABSENT = """\
// This project spells buildutil's annotation vocabulary itself ([reflect]
// macros = "none"), so nothing is defined here and the ground truth is the
// only thing the generator reads: buildutil::label, buildutil::meta and
// buildutil::help, written as attributes.
"""

# What the support header says where the sugar used to be defined. A project
# pointing at its own macro file still reaches it through the same include.
_MACRO_NOTE = {Macros.BUILTIN: _MACRO_INCLUDED,
               Macros.CUSTOM: _MACRO_INCLUDED,
               Macros.NONE: _MACRO_ABSENT}

_MACRO_TEMPLATE = """\
// generated by buildutil — do not edit.
#ifndef BUILDUTIL_REFLECT_MACROS_V1_HPP
#define BUILDUTIL_REFLECT_MACROS_V1_HPP

// The terse spellings of buildutil's annotation vocabulary.
//
//   _Label(x)     an alternative EXTERNAL name for the declaration -- the
//                 name it carries when it leaves the program, for when the
//                 identifier cannot be that name:
//
//                   struct Endpoint {{ bool tls _Label(secure); }};
//                   enum class Level {{ VERBOSE _Label(loud), QUIET }};
//
//   _Help(x)     explicit COMMENT text, overriding the source comment.
//
//   _Meta(...)    free-form tags, captured verbatim and in order, and never
//                 interpreted here: what a tag MEANS belongs to the library
//                 that reads it.
//
// _Label and _Help accept bare text or a string, recovered from the source
// between the parentheses rather than joined from tokens -- so a label the
// lexer would split (content-type is three tokens) still arrives whole.
// _Meta passes its arguments through, so write them as you mean them.
//
// The ground truth under these is a real attribute in buildutil's own
// namespace: label, meta and help. These may be written directly, with
// no macro at all.
//
{prose}
//
// A header that writes either must reach this file. Including
// <_buildutil/reflect.hpp> is enough -- it includes this one -- and that is
// the only route on purpose: a project-wide -D injection would make the
// spelling work with no visible declaration anywhere, and an identifier
// with no findable origin is the kind of magic this generator exists to
// avoid.

{label}
{meta}
{help}

#endif  // BUILDUTIL_REFLECT_MACROS_V1_HPP
"""

_MACRO_FORWARD = """\
// generated by buildutil — do not edit.
#ifndef BUILDUTIL_REFLECT_MACROS_V1_HPP
#define BUILDUTIL_REFLECT_MACROS_V1_HPP

// This project spells its annotations itself ([reflect] macros). The file
// below defines them, and the generator reads the spellings back out of it,
// so the sugar and what the generator recognises cannot drift apart.
#include "{path}"

#endif  // BUILDUTIL_REFLECT_MACROS_V1_HPP
"""


