def _cmd_scan(opts) -> int:
  root = Path(opts.root).resolve()
  sources = Path(opts.sources).resolve()
  generated = Path(opts.generated).resolve()
  detoured = opts.include == "detour"
  try:
    macros = macro_source(opts.macros)
    mode = expansion(opts.annotation)
    if macros.kind is Macros.CUSTOM:
      # Read here as well as at generate time: a file that names no
      # annotation, or misspells one, should refuse the CONFIGURE rather
      # than every header's build rule in turn.
      macro_spellings(macros)
  except AnnotationError as bad:
    sys.stderr.write("buildutil reflect: {}\n".format(bad))
    return 1

  headers = tagged_headers(sources) if sources.is_dir() else []

  if detoured and headers:
    # Before anything is written: a spelling that goes around a detour is
    # that same trap again, and it is cheaper to refuse it here than to let a
    # consumer find it as a static_assert three modules away.
    found = bypasses(sources, headers)
    if found:
      sys.stderr.write(bypass_message(root, found))
      return 1

  source_files = []
  if headers and not detoured:
    for path in sorted(sources.rglob("*")):
      if path.suffix in SOURCE_SUFFIXES and path.is_file() \
         and not _skip_dir(path.relative_to(sources)):
        source_files.append(path)

  mapping = {}
  if headers and opts.include == "source":
    preprocess = None
    if opts.scan == "preprocess" and opts.compiler:
      inc = [str(sources), str(generated)]
      preprocess = lambda src: preprocessor_closure(          # noqa: E731
        opts.compiler, src, [f"-I{p}" for p in inc])
    mapping = sources_needing(source_files, headers, sources,
                              mode=opts.scan, preprocess=preprocess)

  _write(generated / "_buildutil" / "reflect.hpp",
         support_header(opts.namespace, macros))
  if macros.kind is not Macros.NONE:
    _write(generated / MACRO_HEADER, macro_header(mode, macros))
  _write(Path(opts.out),
         declarations(headers, sources, root, mapping, detours=detoured))
  prune(generated, owned(headers, sources, detours=detoured, macros=macros))
  return 0


MANIFEST = "_buildutil/reflect.manifest"

_DETOUR_MARK = "The reflect detour for"


def owned(headers: list[Path], sources: Path, detours: bool,
          macros: "_MacroSource | None" = None) -> list[str]:
  """Every file under the generated root this step is responsible for, as
  generated-root-relative paths."""
  macros = MACROS_BUILTIN if macros is None else macros
  files = ["_buildutil/reflect.hpp"]
  if macros.kind is not Macros.NONE:
    files.append(MACRO_HEADER)
  for header in headers:
    schemes = reflect_rel(header, sources)
    files += [schemes, schemes + ".d"]
    if detours:
      files.append(detour_rel(header, sources))
  return files


def prune(generated: Path, keep: list[str]) -> list[str]:
  """Drop what this step wrote and no longer owns.

  A reflect file left behind by a header that was renamed, deleted or
  untagged is not inert. The generated root sits AHEAD of sources/ on every
  include path, so the orphaned DETOUR goes on shadowing the spelling it
  was made for, and the schemes beside it are frozen at whatever the last
  parse said — a build that stays green and stops telling the truth. The
  deleted-header case is louder and no better: the detour includes a file
  that no longer exists, and the error names a path under the build tree
  that nobody edited.

  Ownership is READ, never guessed: the manifest records what the last scan
  wrote. The generated root is shared with Add_generated_source and the
  configure hooks, and a pruner that inferred ownership from the tree would
  eventually eat one of theirs. Before there is a manifest to read, only
  the two shapes this step alone produces are recognised.
  """
  manifest = generated / MANIFEST
  try:
    had = manifest.read_text(encoding="utf-8").split("\n")
  except OSError:
    had = _reflect_shaped(generated)

  wanted = set(keep)
  gone = []
  for rel in had:
    if not rel or rel in wanted:
      continue
    path = generated / rel
    try:
      path.unlink()
    except OSError:
      continue
    gone.append(rel)
    _drop_empty(path.parent, generated)
  _write(manifest, "".join(rel + "\n" for rel in sorted(wanted)))
  return gone


def _reflect_shaped(generated: Path) -> list[str]:
  """What a scan that kept no manifest left behind: a `*.reflect.hpp` and
  its depfile, whose names belong to nothing else, and the detour beside it,
  which says in its first line what it is."""
  found = []
  if not generated.is_dir():
    return found
  for path in sorted(generated.rglob("*" + REFLECT_SUFFIX)):
    found.append(path.relative_to(generated).as_posix())
    depfile = Path(str(path) + ".d")
    if depfile.is_file():
      found.append(depfile.relative_to(generated).as_posix())
    beside = path.parent / (path.name[:-len(REFLECT_SUFFIX)] + ".hpp")
    if beside.is_file() and _DETOUR_MARK in _first_line(beside):
      found.append(beside.relative_to(generated).as_posix())
  return found


def _first_line(path: Path) -> str:
  try:
    with path.open(encoding="utf-8", errors="replace") as handle:
      return handle.readline()
  except OSError:                                          # pragma: no cover
    return ""


def _drop_empty(directory: Path, stop: Path) -> None:
  while directory != stop and stop in directory.parents:
    try:
      directory.rmdir()
    except OSError:
      return
    directory = directory.parent


_SEVERITY = {1: "note", 2: "warning", 3: "error", 4: "fatal error"}


def _header_text(path: Path) -> str:
  try:
    return path.read_text(encoding="utf-8", errors="replace")
  except OSError:                                          # pragma: no cover
    return ""


def without_hand_written(header: Path, entries: list, enums: list
                         ) -> "tuple[list, list]":
  """What is left for the generator once the header's own definitions are
  taken out. It reads them through the same scanner the promise count does,
  so a type that stops being promised is exactly the one that stops being
  emitted.
  """
  written = hand_written(_header_text(header))
  return ([entry for entry in entries if entry.name not in written],
          [entry for entry in enums if entry.name not in written])


def shortfall(header: Path, entries: list, enums: list
              ) -> "tuple[list[str], list[str], list[str]] | None":
  """What the header PROMISED, against what the parse produced.

  The parse runs with KeepGoing, which is the right setting -- one
  unreachable include should not cost every other type in the file -- but it
  means a type whose base class never resolved comes back invalid, gets
  skipped, and leaves no trace. The header itself is the record of what
  should have been there, and it is the same count the scan took.
  """
  promised = tag_declarations(_header_text(header))
  emitted = [entry.name for entry in enums] + [entry.name for entry in entries]
  if len(emitted) >= len(promised):
    # COUNTS are the gate, not names: a name this side read differently from
    # the way clang spells it must not invent a shortfall out of nothing.
    return None
  missing = collections.Counter(name for name in promised if name)
  missing.subtract(collections.Counter(emitted))
  return promised, emitted, sorted(missing.elements())


def diagnostics(tu, limit: int = 25) -> list[str]:
  """Everything clang said at warning and above. They exist -- KeepGoing
  collects them -- and until now nothing ever printed them, which is exactly
  why a dropped type looked like nothing at all happening."""
  out = []
  for diagnostic in tu.diagnostics:
    if diagnostic.severity < 2:
      continue
    where = diagnostic.location
    place = "{}:{}:{}".format(
      Path(where.file.name).name if where.file else "<none>",
      where.line, where.column)
    out.append("{}: {}: {}".format(
      place, _SEVERITY.get(diagnostic.severity, "?"), diagnostic.spelling))
    if len(out) == limit:
      out.append("... and more")
      break
  return out


def shortfall_message(header: Path, promised: list[str], emitted: list[str],
                      missing: list[str], includes: list[str],
                      said: list[str]) -> str:
  lines = ["buildutil reflect: {}".format(header),
           "  {} type(s) tagged, {} scheme(s) emitted".format(
             len(promised), len(emitted))]
  if missing:
    lines.append("  no scheme for: {}".format(", ".join(missing)))
  lines += [
    "",
    "  A tagged type that produces no scheme almost always means an include",
    "  directory the generator was not given: a header this one reaches for",
    "  does not resolve, the type it needed stays unresolved, and the parse",
    "  keeps going without it. The include directories in force were:"]
  lines += ["      {}".format(path) for path in includes] or ["      (none)"]
  if said:
    lines += ["", "  clang said:"]
    lines += ["      {}".format(line) for line in said]
  else:
    lines += ["", "  clang reported nothing, so look instead for a tag whose",
              "  type is declared in another header, or a form this",
              "  generator refuses (a non-type template parameter)."]
  return "\n".join(lines) + "\n"


def _cmd_generate(opts) -> int:
  header = Path(opts.header).resolve()
  output = Path(opts.output)
  includes = opts.include_dir or []
  try:
    ci, resource = load_clang()
  except ClangUnavailable as missing:
    sys.stderr.write("buildutil reflect: {}\n".format(missing))
    return 1
  args = parse_args(opts.std, includes, resource, sdk_path(), msvc_args())
  tu = parse(ci, header, args)

  try:
    macros = macro_spellings(macro_source(opts.macros))
    entries = collect(ci, tu, header, macros)
    enums = collect_enums(ci, tu, header, macros)
  except AnnotationError as bad:
    # Nothing is written. An annotation buildutil does not define is a typo,
    # and a typo that produced a half-annotated header would be found later,
    # somewhere else, as an absence.
    sys.stderr.write("buildutil reflect: {}\n".format(bad))
    return 1

  entries, enums = without_hand_written(header, entries, enums)
  short = shortfall(header, entries, enums)
  if short is not None:
    # Loudly, and with nothing written: a half-populated reflect header on
    # disk is what turned this into a static_assert three modules away.
    sys.stderr.write(shortfall_message(header, *short, includes,
                                       diagnostics(tu)))
    return 1

  include_spelling = opts.include_spelling or header.name
  # A detoured reflect header is included one line below its own header and
  # must not name it again; a force-included one is the top of the TU and
  # must. The presence of --detour is the whole of that distinction.
  _write(output, emit(entries, include_spelling, opts.namespace, enums,
                      back_include=not opts.detour))
  if opts.detour:
    if not opts.sources:
      sys.stderr.write("buildutil reflect: --detour needs --sources, to know "
                       "what this header's own include spelling is\n")
      return 1
    # cmake's spellings and not the resolved ones: a tree reached through a
    # symlink should name itself the way its author does, and `#pragma once`
    # dedupes by file identity whichever path arrives.
    #
    # Path-only content, so this is near-constant across a project's life --
    # and _write's content diff is what keeps its mtime from restamping every
    # consumer of a header whose schemes merely got rebuilt.
    _write(Path(opts.detour), detour(Path(opts.header), Path(opts.sources)))
  if opts.depfile:
    _write(Path(opts.depfile), depfile(output, tu, header))
  return 0


def _write(path: Path, text: str) -> None:
  """Content-diffed, like every other write in buildutil: an unchanged output
  must not restamp a file and churn the build."""
  path.parent.mkdir(parents=True, exist_ok=True)
  if path.is_file() and path.read_text(encoding="utf-8") == text:
    return
  path.write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(prog="python -m buildutil.reflect")
  sub = parser.add_subparsers(dest="verb", required=True)

  scan = sub.add_parser("scan", help="find tagged headers (configure time)")
  scan.add_argument("--root", required=True)
  scan.add_argument("--sources", required=True)
  scan.add_argument("--generated", required=True)
  scan.add_argument("--out", required=True)
  scan.add_argument("--namespace", default="reflect")
  scan.add_argument("--scan", default="direct",
                    choices=("direct", "preprocess"))
  scan.add_argument("--include", default="detour",
                    choices=("detour", "source", "module"))
  scan.add_argument("--annotation", default=Expansion.MACRO.value,
                    help="what the shipped _Label/_Meta macros expand to")
  scan.add_argument("--macros", default=Macros.BUILTIN.value,
                    help="auto | none | path to the project's own macro file")
  scan.add_argument("--compiler", default="")
  scan.set_defaults(func=_cmd_scan)

  gen = sub.add_parser("generate", help="parse one header (build time)")
  gen.add_argument("--header", required=True)
  gen.add_argument("--output", required=True)
  gen.add_argument("--detour", default="",
                   help="also write the wrapper header at this path")
  gen.add_argument("--sources", default="",
                   help="the sources root, for the detour's own spelling")
  gen.add_argument("--depfile", default="")
  gen.add_argument("--namespace", default="reflect")
  gen.add_argument("--macros", default=Macros.BUILTIN.value,
                   help="auto | none | path to the project's own macro file")
  gen.add_argument("--std", default="c++23")
  gen.add_argument("--include-dir", action="append")
  gen.add_argument("--include-spelling", default="")
  gen.set_defaults(func=_cmd_generate)

  opts = parser.parse_args(argv)
  return opts.func(opts)


